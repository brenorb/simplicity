#!/bin/sh
# Generate the plain-field what-if variant of the BN254 precompile relations.
# Same curve code; the field multiply is JetDiscovery.Corpus.BN254.fpMul
# (a*b mod p, the bn254_fp_multiply candidate's specification) and the
# Montgomery conversions become the identity.  Used for static cost only.
set -eu
src=followup/src/JetDiscovery/Followup/Bn254Precompiles.hs
dst=followup/src/JetDiscovery/Followup/Bn254PrecompilesPlain.hs
sed -e 's/^module JetDiscovery.Followup.Bn254Precompiles$/module JetDiscovery.Followup.Bn254PrecompilesPlain/' \
    -e 's/^import JetDiscovery.Lib.Bytes (konst)$/import JetDiscovery.Lib.Bytes (konst)\nimport qualified JetDiscovery.Corpus.BN254 as Field/' \
    -e 's/^oneM = .*/oneM = 1/' \
    -e 's/^threeM = .*/threeM = 3/' \
    -e 's/^montMul = .*/montMul = Field.fpMul/' \
    -e 's/^toM = .*/toM = iden/' \
    -e 's/^fromM = .*/fromM = iden/' \
    -e 's/Core term =>/Assert term =>/g' \
    -e 's/(Core term, /(Assert term, /g' \
    -e 's/^-- | Exact EIP-196 BN254 G1 precompile relations/-- | GENERATED by tools\/gen_bn254_plain.sh: plain-field what-if variant of the EIP-196 relations/' \
    -e '/^  m = (ih &&& kw npBN)/d' \
    -e '/^  redc = (iden &&& ((m &&& kw pBN)/d' \
    "$src" > "$dst"
# montMul's now-empty 'where' line
sed -i.bak '/^montMul = Field.fpMul$/{n;/^ where$/d;}' "$dst" && rm -f "$dst.bak"
