#!/usr/bin/env python3
"""Generate followup/src/JetDiscovery/Followup/Bn254PairingDag.hs from Bn254Pairing.hs.

The twin instantiates every term at T = JetDag JetType, so each closed
operation is one shared top-level value (NOINLINE).  The polymorphic module
re-interprets wrapped operations at every use site, which exhausts memory when
building a full pairing program.  Semantics are unchanged; only the type is
fixed.  Run from jet-discovery/.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = (ROOT / 'followup/src/JetDiscovery/Followup/Bn254Pairing.hs').read_text()
s = src[:src.index('\n{-# NOINLINE f2mulTW #-}')] + '\n'
i, j = s.index('-- Memoised building blocks'), s.index('-- Fp2 -----')
mono = '''-- Shared building blocks -----------------------------------------------------------
-- This module is the generated monomorphic twin of Bn254Pairing: every term has
-- the concrete type T = JetDag JetType, so each closed operation below is one
-- shared top-level value, built once and referenced by every use site.

type T = Dag.JetDag J.JetType

{-# NOINLINE montMulD #-}
montMulD :: T (Fp, Fp) Fp
montMulD = PC.montMul
{-# NOINLINE addPD #-}
addPD :: T (Fp, Fp) Fp
addPD = PC.addP
{-# NOINLINE subPD #-}
subPD :: T (Fp, Fp) Fp
subPD = PC.subP

add2, sub2, mul2 :: TyC s => T s Fp -> T s Fp -> T s Fp
add2 a b = (a &&& b) >>> addPD
sub2 a b = (a &&& b) >>> subPD
mul2 a b = (a &&& b) >>> montMulD
dbl :: TyC s => T s Fp -> T s Fp
dbl a = add2 a a

'''
s = s[:i] + mono + s[j:]
s = s.replace('module JetDiscovery.Followup.Bn254Pairing\n', 'module JetDiscovery.Followup.Bn254PairingDag\n')
s = s.replace('import qualified Simplicity.Bitcoin.Jets as J\n', 'import qualified Simplicity.Bitcoin.Jets as J\nimport qualified Simplicity.Bitcoin.Dag as Dag\n')
s = s.replace('  , finalExpT, millerT, subgroupT, pairT\n', '  , finalExpT, millerT, subgroupT, pairT, T\n')
for n in ["f2mulT", "f2sqT", "f6mulT", "f12mulT", "f12sqT", "frobT", "powUT"]:
    s = re.sub(r'\b' + n + r'0\b', n, s)
s = s.replace('forall term. ', '')
s = re.sub(r'\(Simplicity term, TyC (\w+)\) => ', r'TyC \1 => ', s)
s = s.replace('Simplicity term => ', '')
s = re.sub(r'\bterm (?=[(A-Z\w])', 'T ', s)
cafs = ["f2addT", "f2subT", "f2mulT", "f2sqT", "f2negT", "f2conjT", "f2mulXiT", "f6mulT", "f6addT", "f6subT", "f6negT",
        "f6mulVT", "f12mulT", "f12sqT", "conj12T", "frobT", "frob2T", "powUT"]
for n in cafs:
    s = re.sub(r'(?m)^(' + n + r' = )', '{-# NOINLINE ' + n + ' #-}\n\\1', s, count=1)
s = s.replace('-- | Exact EIP-197 BN254 pairing-check relation',
              '-- | GENERATED by tools/gen_bn254_pairing_dag.py from Bn254Pairing.hs: monomorphic twin.\n-- Exact EIP-197 BN254 pairing-check relation')
(ROOT / 'followup/src/JetDiscovery/Followup/Bn254PairingDag.hs').write_text(s)
