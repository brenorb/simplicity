main :: IO ()
main = do
  hSetBuffering stdout LineBuffering
  args <- getArgs
  case args of
    [] -> runAll
    ["run"] -> runAll
    ["run", prefix] -> runSome prefix
    ["verify", prefix] -> verifySome prefix
    ["profile", i] -> profileOne i
    ["time", i] -> timeOne i
    ["index"] -> writeIndex
    ["metadata"] -> writeMetadata
    ["stark-reference"] -> do
      putStrLn "generating and checking full-size Fibonacci STARK reference proof"
      hFlush stdout
      ok <- evaluate (FS.verify FS.realistic (FS.prove FS.realistic))
      print ok
      unless ok exitFailure
    _ -> putStrLn "usage: jet-discovery [run [prefix] | verify <prefix> | profile <id> | time <id> | index | metadata | stark-reference]"

-- Inventory only: force no Simplicity expression, cost or proof. Keeping this
-- in the ordinary executable avoids separate GHCi/Backpack package loading.
writeMetadata :: IO ()
writeMetadata = do
  es <- corpus
  putStrLn "id\ttitle\tcategory\tspec\tvector_source\tvectors\tassumptions"
  forM_ es $ \(Entry ident title spec category source assumptions _ vectors) ->
    putStrLn (intercalate "\t" (map clean [ident,title,show category,spec,show source,
      show (length vectors),intercalate "; " assumptions]))
 where
  clean = map (\c -> if c `elem` "\t\r\n" then ' ' else c)

-- | Write corpus/README.md: one section per program (spec, vectors, assumptions, module).
writeIndex :: IO ()
writeIndex = do
  es <- corpus
  writeFile "corpus/README.md" $ unlines $
    [ "# Corpus"
    , ""
    , "Generated by `jet-discovery index` from the entries in `src/JetDiscovery/Corpus/`.  Each program is Haskell"
    , "(the in-tree Simplicity eDSL); its vectors are run by `jet-discovery run`.  Upstream vector files live in"
    , "`vendor-specs/` (see vendor-specs/MANIFEST.md).  Results: reports/corpus-results.md."
    , "" ] ++ concatMap section es
 where
  section e =
    [ "## `" ++ entryId e ++ "` — " ++ entryTitle e
    , ""
    , "- Category: " ++ show (entryCategory e)
    , "- Spec: " ++ entrySpec e
    , "- Vectors (" ++ show (vectorCount e) ++ "): " ++ showSource (entryVectorSource e)
    , "- Assumptions:" ] ++ [ "  - " ++ a | a <- entryAssumptions e ] ++ [""]
  showSource (Upstream x) = "upstream — " ++ x
  showSource (Derived x) = "derived — " ++ x
  vectorCount (Entry _ _ _ _ _ _ _ vs) = length vs

runAll :: IO ()
runAll = do
  writeIndex
  fp <- sourceFingerprint
  rs <- mapM (runCached fp) =<< corpus
  let bad = filter (not . vectorsOk) rs
  unless (null bad) $ do
    putStrLn ("FAILED; generated analysis reports preserved: " ++ unwords (map (entryId . erEntry) bad))
    exitFailure
  createDirectoryIfMissing True "reports/data"
  writeFile "reports/data/corpus-results.tsv" (resultsTsv rs)
  writeFile "reports/data/candidate-impact.tsv" (candidateImpactTsv rs)
  writeFile "reports/data/run-fingerprint.txt" (fp++"\n")
  writeFile "reports/candidate-impact.md" $ unlines
    ["# Isolated candidate costs (ESTIMATE)","",
     "Generated by `jet-discovery run`. Each row adds exactly one candidate to the existing Bitcoin jets, including matches hidden inside other candidate expressions and changes to the most expensive case branch.",
     "Rows are alternative counterfactuals: savings do not add. Occurrences count the selected static-bound path. Both WOTS frontends belong to one primitive family. The complete matrix, including zero-match rows, is in data/candidate-impact.tsv.",
     "Feasibility holds the original serialized stack's hypothetical witness-bytes + 50 budget fixed (METHOD.md). Candidate encodings and their new program lengths are undefined. This is not an established Bitcoin rule or deployment claim. Prices require C benchmarks and proofs.","",candidateImpactMarkdown rs]
  writeFile "reports/corpus-results.md" (header ++ resultsMarkdown rs)
  let variantRows = [ (fam, pid, measure p) | (fam, pid, p) <- variants ]
  writeFile "reports/whatif.md" $ unlines $
    [ "# What-if costs with candidate jets (ESTIMATE)"
    , ""
    , "Generated by `jet-discovery run`.  The overlay (JetDiscovery.WhatIf) replaces every occurrence of a candidate's"
    , "specification with a jet priced at its ESTIMATE cost (JetDiscovery.Candidates.Registry).  Costs are static bounds."
    , ""
    , whatIfMarkdown rs
    , "## Stand-in variants (cost only, never executed)"
    , ""
    , "See JetDiscovery.Candidates.Variants: the exact programs rewritten with stand-in jets of analogous cost."
    , ""
    , "| candidate family | program | measured cost (WU) | variant cost (WU, ESTIMATE) | saving |"
    , "| --- | --- | ---: | ---: | ---: |" ] ++
    [ "| " ++ fam ++ " | `" ++ pid ++ "` | " ++ wu c ++ " | " ++ wu (mCost vm) ++ " | " ++ showFFloat (Just 1) (fromInteger c / fromInteger (mCost vm) :: Double) "×" ++ " |"
    | (fam, pid, vm) <- variantRows, let c = head ([ mCost (erMeasure r) | r <- rs, entryId (erEntry r) == pid ] ++ [0]) ]
  writeFile "reports/ablations.md" $ unlines
    [ "# Costs with jet families removed"
    , ""
    , "Generated by `jet-discovery run`.  Each program is re-costed with a family of existing jets removed"
    , "(JetDiscovery.JetSets.Ablate): what the program would cost if those jets did not exist.  Only programs that"
    , "use the family are listed.  These are measurements, not estimates."
    , ""
    , ablationMarkdown rs ]
  let corpusTotal = sum (map (mCost . erMeasure) rs)
      exact = mine False rs
      shapes = mine True rs
  writeFile "reports/data/subdags-exact.tsv" (groupsTsv exact)
  writeFile "reports/data/subdags-shape.tsv" (groupsTsv shapes)
  writeFile "reports/subdags.md" $ unlines
    [ "# Repeated expensive sub-DAGs"
    , ""
    , "Generated by `jet-discovery run` (JetDiscovery.Mine).  Nodes of the jet-substituted DAGs of all "
      ++ show (length rs) ++ " corpus programs, total static bound " ++ wu corpusTotal ++ " WU."
    , "A sub-DAG's \"total WU\" is multiplicity x its static bound, summed over programs: the part of the corpus's"
    , "cost spent inside it.  Only repeated sub-DAGs (multiplicity >= 2, or in >= 2 programs) of at least 1 WU that"
    , "are not already a single jet are listed.  Nested sub-DAGs overlap, so shares do not add up."
    , ""
    , "## By shape (constant word values ignored)"
    , ""
    , groupsMarkdown corpusTotal 60 shapes
    , "## By exact structure"
    , ""
    , groupsMarkdown corpusTotal 40 exact ]
  putStrLn ("all " ++ show (length rs) ++ " corpus programs pass their vectors")
 where
  header = unlines
    [ "# Corpus results"
    , ""
    , "Generated by `jet-discovery run`.  Costs are static cost bounds (the same bound C/eval.c checks against the budget)."
    , "\"assumed budget\" uses the ASSUMPTION budget = witness stack bytes + 50 WU (see reports/METHOD.md); the Bitcoin rule is not defined in this repository."
    , "" ]

-- | Run only entries whose id starts with the prefix (development; writes no reports).
-- Vector-only development path: checks the real jetted CMR and execution,
-- prints each result immediately, and does not claim cost/analysis coverage.
verifySome :: String -> IO ()
verifySome prefix = do
  entries<-filter (\e -> take (length prefix) (entryId e)==prefix) <$> corpus
  when (null entries) $ putStrLn ("no program matches prefix: "++prefix) >> exitFailure
  failed<-newIORef False
  forM_ entries $ \e@(Entry _ _ _ _ _ _ program vectors) -> do
    putStrLn ("verifying "++entryId e)
    let cmr=case vectors of v:_ -> progCmr (program (vecWitness v)); [] -> error "entry has no vectors"
    forM_ (runVectors program cmr vectors) $ \result -> do
      ok<-evaluate (vrOk result)
      putStrLn (entryId e++" / "++vrName result++": "++(if ok then "PASS" else "FAIL")++" ("++vrNote result++")")
      unless ok (writeIORef failed True)
  bad<-readIORef failed
  when bad exitFailure
  putStrLn (show (length entries)++" programs pass their vectors; costs not measured")

runSome :: String -> IO ()
runSome prefix = do
  es <- filter (\e -> take (length prefix) (entryId e) == prefix) <$> corpus
  when (null es) $ putStrLn ("no program matches prefix: " ++ prefix) >> exitFailure
  fp <- sourceFingerprint
  rs <- mapM (runCached fp) es
  let bad = filter (not . vectorsOk) rs
  unless (null bad) $ putStrLn ("FAILED: " ++ unwords (map (entryId . erEntry) bad)) >> exitFailure
  putStrLn (show (length rs) ++ " programs pass")

-- Plain-data checkpoints let an interrupted multi-hour run resume without
-- retaining every term interpreter graph. Fingerprints bind sources, vectors,
-- build settings, and the actual executable; stale or failing rows rerun.
runCached :: String -> Entry -> IO EntryResult
runCached fp e = do
  let dir="dist-newstyle/jet-discovery-results"
  cached<-loadResult dir fp e
  case cached of
    Just r | vectorsOk r -> do
      putStrLn (entryId e ++ " ... " ++ wu (mCost (erMeasure r)) ++ " WU (verified checkpoint)")
      return r
    _ -> do
      r<-runOne e
      saveResult dir fp r
      -- Re-read to retain the compact profile, rather than closures pointing
      -- back into jet matching, type inference, and source DAG construction.
      detached<-loadResult dir fp e
      case detached of
        Just result -> return result
        Nothing -> error "snapshot round-trip failed"

runOne :: Entry -> IO EntryResult
runOne e = do
  putStrLn ("running " ++ entryId e ++ " (vectors and static analysis)")
  hFlush stdout
  r <- runEntryIO e
  let m = erMeasure r
  putStr (entryId e ++ " ... ")
  when (mProfileTotal m /= mCost m) $
    putStr ("[profile mismatch " ++ show (mProfileTotal m) ++ " vs " ++ show (mCost m) ++ "] ")
  when (not (null (mProfile m)) && niCmr (last (mProfile m)) /= mCmr m) $
    putStr "[profile CMR mismatch] "
  forM_ (erVectors r) $ \v -> unless (vrOk v) $ putStr ("[vector failed: " ++ vrName v ++ " (" ++ vrNote v ++ ")] ")
  putStrLn (wu (mCost m) ++ " WU")
  return r

profileOne :: String -> IO ()
profileOne i = corpus >>= \c -> case [ e | e <- c, entryId e == i ] of
  [e] -> do
    let m = erMeasure (runEntry e)
        total = mCost m
        top = take 40 . sortBy (comparing (Down . \n -> niMult n * niTotal n)) $ filter (\n -> niMult n > 0) (mProfile m)
    putStrLn ("total " ++ wu total ++ " WU, " ++ show (mNodes m) ++ " DAG nodes")
    forM_ top $ \n -> putStrLn $ concat
      [ pct (niMult n * niTotal n) total, "\t", wu (niTotal n), " WU x", show (niMult n), "\t", niKind n, " : "
      , prettyTy (niSrc n), " -> ", prettyTy (niTgt n) ]
  _ -> putStrLn "unknown id"

-- | Time each measurement phase of one entry (diagnostics).
timeOne :: String -> IO ()
timeOne i = corpus >>= \c -> case [ e | e <- c, entryId e == i ] of
  [Entry _ _ _ _ _ _ prog (v:_)] -> do
    let m = measure (prog (vecWitness v))
        t l a = do { s0 <- getCPUTime; value <- evaluate a; s1 <- getCPUTime
                   ; putStrLn (l ++ " result=" ++ show value ++ " cpu_seconds=" ++ show (fromIntegral (s1 - s0) / 1e12 :: Double)) }
    t "cmr" (mCmr m)
    t "cost" (mCost m)
    t "baseline" (mCostBase m)
    t "whatif" (mCostWhatIf m)
    t "isolated candidate scenarios" (sum [cost+count|(_, (cost,count))<-mCandidateCosts m])
    t "bits" (mProgBits m + mWitBits m)
    t "profile" (mProfileTotal m)
    forM_ (mAblations m) $ \(name,cost) -> t ("ablation:"++name) cost
    unless (mProfileTotal m==mCost m && niCmr (last (mProfile m))==mCmr m) $ do
      putStrLn "profile consistency failed"
      exitFailure
    let passed=all vrOk (runVectors prog (mCmr m) [v])
    t "one vector" passed
    unless passed exitFailure
  _ -> putStrLn "unknown id"

