-- | jet-discovery command line.
--
-- > jet-discovery run            -- run all corpus vectors, measure, write reports/
-- > jet-discovery profile <id>   -- print the most expensive sub-DAGs of one program
module Main (main) where

import Control.Monad (forM_, unless, when)
import Data.List (sortBy)
import Data.Ord (comparing, Down(..))
import System.Directory (createDirectoryIfMissing)
import System.Environment (getArgs)
import System.Exit (exitFailure)
import System.IO (hFlush, stdout)
import System.CPUTime (getCPUTime)
import Control.Exception (evaluate)

import JetDiscovery.Corpus (corpus)
import JetDiscovery.Corpus.Hashes (debugBlake2s)
import qualified Simplicity.Bitcoin.Jets as Jets
import Simplicity.Ty.Word (fromWord32)
import Numeric (showHex)
import JetDiscovery.Tx (mkEnv, mkTx, mkInput, mkOutput, dummyOutpoint, defaultTap)
import Simplicity.Digest (hash0)
import JetDiscovery.Profile (NodeInfo(..), prettyTy)
import JetDiscovery.Report
import JetDiscovery.Run
import JetDiscovery.Types

main :: IO ()
main = do
  args <- getArgs
  case args of
    [] -> runAll
    ["run"] -> runAll
    ["run", prefix] -> runSome prefix
    ["profile", i] -> profileOne i
    ["time", i] -> timeOne i
    ["debug-blake", n] -> debugBlake (read n)
    _ -> putStrLn "usage: jet-discovery [run | profile <id>]"

runAll :: IO ()
runAll = do
  rs <- mapM runOne =<< corpus
  createDirectoryIfMissing True "reports/data"
  writeFile "reports/data/corpus-results.tsv" (resultsTsv rs)
  writeFile "reports/corpus-results.md" (header ++ resultsMarkdown rs)
  let bad = filter (not . vectorsOk) rs
  unless (null bad) $ do
    putStrLn ("FAILED: " ++ unwords (map (entryId . erEntry) bad))
    exitFailure
  putStrLn ("all " ++ show (length rs) ++ " corpus programs pass their vectors")
 where
  header = unlines
    [ "# Corpus results"
    , ""
    , "Generated by `jet-discovery run`.  Costs are static cost bounds (the same bound C/eval.c checks against the budget)."
    , "\"assumed budget\" uses the ASSUMPTION budget = witness stack bytes + 50 WU (see reports/METHOD.md); the Bitcoin rule is not defined in this repository."
    , "" ]

-- | Run only entries whose id starts with the prefix (development; writes no reports).
runSome :: String -> IO ()
runSome prefix = do
  es <- filter (\e -> take (length prefix) (entryId e) == prefix) <$> corpus
  rs <- mapM runOne es
  let bad = filter (not . vectorsOk) rs
  unless (null bad) $ putStrLn ("FAILED: " ++ unwords (map (entryId . erEntry) bad)) >> exitFailure
  putStrLn (show (length rs) ++ " programs pass")

runOne :: Entry -> IO EntryResult
runOne e = do
  r <- runEntryIO e
  let m = erMeasure r
  putStr (entryId e ++ " ... ")
  when (mProfileTotal m /= mCost m) $
    putStr ("[profile mismatch " ++ show (mProfileTotal m) ++ " vs " ++ show (mCost m) ++ "] ")
  forM_ (erVectors r) $ \v -> unless (vrOk v) $ putStr ("[vector failed: " ++ vrName v ++ " (" ++ vrNote v ++ ")] ")
  putStrLn (wu (mCost m) ++ " WU")
  return r

profileOne :: String -> IO ()
profileOne i = corpus >>= \c -> case [ e | e <- c, entryId e == i ] of
  [e] -> do
    let m = erMeasure (runEntry e)
        total = mCost m
        top = take 40 . sortBy (comparing (Down . \n -> niMult n * niTotal n)) $ filter (\n -> niMult n > 0) (mProfile m)
    putStrLn ("total " ++ wu total ++ " WU, " ++ show (mNodes m) ++ " DAG nodes")
    forM_ top $ \n -> putStrLn $ concat
      [ pct (niMult n * niTotal n) total, "\t", wu (niTotal n), " WU x", show (niMult n), "\t", niKind n, " : "
      , prettyTy (niSrc n), " -> ", prettyTy (niTgt n) ]
  _ -> putStrLn "unknown id"

-- | Time each measurement phase of one entry (diagnostics).
timeOne :: String -> IO ()
timeOne i = corpus >>= \c -> case [ e | e <- c, entryId e == i ] of
  [Entry _ _ _ _ _ _ prog (v:_)] -> do
    let m = measure (prog (vecWitness v))
        t l a = do { s0 <- getCPUTime; _ <- evaluate a; s1 <- getCPUTime
                   ; putStrLn (l ++ ": " ++ show (fromIntegral (s1 - s0) / 1e12 :: Double) ++ "s") }
    t "cmr" (mCmr m `seq` ())
    t "cost" (mCost m)
    t "baseline" (mCostBase m)
    t "whatif" (mCostWhatIf m)
    t "bits" (mProgBits m + mWitBits m)
    t "profile" (mProfileTotal m)
    t "one vector" (length (filter vrOk (runVectors prog (mCmr m) [v])))
  _ -> putStrLn "unknown id"

debugBlake :: Int -> IO ()
debugBlake n = do
  let Just env = mkEnv (mkTx 2 [mkInput (dummyOutpoint 0) 1000 mempty 0] [mkOutput 900 mempty] 0) 0 defaultTap hash0
      flat ((((a,b),(c,d)),((e,f),(g,h))),(((i,j),(k,l)),((m,n'),(o,p)))) = [a,b,c,d,e,f,g,h,i,j,k,l,m,n',o,p]
  case Jets.fastEval (debugBlake2s n) env () of
    Just v -> putStrLn (unwords [ showHex (fromWord32 x) "" | x <- flat v ])
    Nothing -> putStrLn "failed"
