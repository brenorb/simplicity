#!/usr/bin/env python3
"""Generate startup/proofs/jet_sha_startup_runs.v.

For each total or partial contract `X_startup_spec` of jet_sha_startup_jets.v,
emit `X_startup_runs`: the jet runs on freshly constructed frames in any
memory satisfying the startup invariant, for every input.  Function, types
and specification come from the type of `X_startup_spec` (not restated); a
`memcpy_model` premise is kept where the contract has one.
"""
import re, sys

src, out_path = sys.argv[1:3]
text = open(src).read()
names = re.findall(r"^Theorem (\w+)_startup_spec :( memcpy_model ->)?", text, re.M)
if len(names) != 18:
    sys.exit("expected 18 contracts, found %d" % len(names))
out = ['''(** GENERATED by startup/gen-startup-runs.py; do not edit.

    Each SHA-unit jet with a total or assertion contract over the startup
    invariant runs on freshly constructed frames, for every input, in any
    memory satisfying the invariant, and re-establishes it. *)
From Coq Require Import ZArith.
From compcert Require Import Integers.
Require Import C.jet_memcpy_model.
Require Import JetStartup.jet_sha_startup_state JetStartup.jet_sha_startup_executable.
Require JetStartup.jet_sha_startup_jets.

Local Ltac bound := vm_compute; discriminate.
Local Ltac runs_type T :=
  lazymatch T with
  | memcpy_model -> ?S => let R := runs_type S in constr:(memcpy_model -> R)
  | sha_startup_total_spec ?f ?A ?B ?s => constr:(sha_total_runs_on_fresh_frames f A B s)
  | sha_startup_partial_spec ?f ?A ?B ?s => constr:(sha_partial_runs_on_fresh_frames f A B s)
  end.
Local Ltac run :=
  first [apply sha_startup_total_executable | apply sha_startup_partial_executable];
  [|bound|bound].
''']
for name, cond in names:
    full = "JetStartup.jet_sha_startup_jets.%s_startup_spec" % name
    if cond:
        proof = "  intros Hmodel. run. exact (%s Hmodel)." % full
    else:
        proof = "  run. exact %s." % full
    out.append('''Theorem %s_startup_runs :
  ltac:(let T := type of %s in let R := runs_type T in exact R).
Proof.
%s
Qed.
''' % (name, full, proof))
open(out_path, "w").write("\n".join(out))
