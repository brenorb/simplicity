#!/usr/bin/env python3
"""Port the proofs about the Bitcoin environment builders (bitcoin-env/C) to
the Elements environment unit.  [simplicity_elements_mallocTapEnv] has the
same C text as the Bitcoin function up to the names of the two structures
and of [make_tapleaf]; the structures have the same members.  The ported
modules are checked by Coq against the Elements program (statement shapes by
[reflexivity], field offsets by computation).  Only the C-side results are
ported: the links to canonical hash values use Bitcoin specification modules.

Usage: gen-elements-env-ports.py OUTDIR   (run from Coq/)"""
import re, sys
out = sys.argv[1]
MODULES = ["jet_env_store_words", "jet_bitcoin_env_field_eval", "jet_bitcoin_env_tomidstate",
           "jet_bitcoin_env_malloc", "jet_bitcoin_env_ctxo", "jet_bitcoin_env_tapenv_prelude",
           "jet_bitcoin_env_tapenv_key", "jet_bitcoin_env_tapenv_fill", "jet_bitcoin_env_tapenv_cmr",
           "jet_bitcoin_env_tapenv_loop", "jet_bitcoin_env_tapenv_path", "jet_bitcoin_env_tapenv_tail",
           "jet_bitcoin_env_tapenv", "jet_bitcoin_env_free"]
SUBS = [("jet_bitcoin_env_", "jet_elements_env_"),
        ("simplicity_bitcoin_freeTransaction", "simplicity_elements_freeTransaction"),
        ("simplicity_bitcoin_freeTapEnv", "simplicity_elements_freeTapEnv"),
        ("_bitcoinTransaction", "_elementsTransaction"),
        ("C.jet_bitcoin_make_tapleaf_exec", "C.jet_elements_make_tapleaf_exec"),
        ("f_simplicity_bitcoin_mallocTapEnv", "f_simplicity_elements_mallocTapEnv"),
        ("simplicity_bitcoin_mallocTapEnv", "simplicity_elements_mallocTapEnv"),
        ("f_simplicity_bitcoin_make_tapleaf", "f_simplicity_make_tapleaf"),
        ("_simplicity_bitcoin_make_tapleaf", "_simplicity_make_tapleaf"),
        ("simplicity_bitcoin_make_tapleaf", "simplicity_make_tapleaf"),
        ("_rawBitcoinTapEnv", "_rawElementsTapEnv"), ("_bitcoinTapEnv", "_elementsTapEnv"),
        ("_rawBitcoinBuffer", "_rawElementsBuffer"),
        ("rawBitcoinTapEnv", "rawElementsTapEnv"), ("bitcoinTapEnv", "elementsTapEnv"),
        ("eval_make_tapleaf", "el_eval_make_tapleaf"), ("make_tapleaf_regs", "el_make_tapleaf_regs"),
        ("sha_tapleaf_tag_ok", "el_sha_tapleaf_tag_ok"),
        ("bitcoin/env.c", "elements/env.c"), ("bitcoin-env/", "elements-env/"),
        ("[jet_bitcoin_field_eval]", "[jet_b1tcoin_field_eval]"), ("the Bitcoin", "the Elements")]
for mod in MODULES:
    t = open("bitcoin-env/C/%s.v" % mod).read()
    for old, new in SUBS:
        t = t.replace(old, new)
    t = t.replace('"TapLeaf" tag', '"TapLeaf/elements" tag')
    left = re.findall(r".{0,30}[Bb]itcoin.{0,30}", t)
    if left:
        sys.exit("%s: unported reference: %r" % (mod, left[:3]))
    t = t.replace("[jet_b1tcoin_field_eval]", "[jet_bitcoin_field_eval]")
    name = mod.replace("jet_bitcoin_env_", "jet_elements_env_")
    t = "(** GENERATED by elements-env/gen-elements-env-ports.py from bitcoin-env/C/%s.v; do not edit. *)\n" % mod + t
    open("%s/%s.v" % (out, name), "w").write(t)
print("ported %d modules" % len(MODULES))
