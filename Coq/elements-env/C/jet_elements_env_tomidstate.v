(** The call: the final memory is the initial one with the eight words
    stored at [midstate]. *)
Theorem eval_sha256_toMidstate m :
  tm_bytes_ok m ->
  Mem.range_perm m bm (Ptrofs.unsigned om) (Ptrofs.unsigned om + 32) Cur Writable ->
  exists m',
    store_words m bm (Ptrofs.unsigned om) tm_words = Some m' /\
    Clight2.eval_funcall sha_ge m (Internal f_sha256_toMidstate) [Vptr bm om; Vptr bh oh] E0 m' Vundef.
Proof.
  intros HB HP.
  set (le0 := PTree.set _hash (Vptr bh oh) (PTree.set _midstate (Vptr bm om)
    (create_undef_temps (fn_temps f_sha256_toMidstate)))).
  destruct (tm_from_exec 7 0%nat le0 m eq_refl HB eq_refl eq_refl) as [le' [m' [HS HE]]].
  { rewrite Z.mul_0_r, Z.add_0_r. exact HP. }
  rewrite Z.mul_0_r, Z.add_0_r in HS.
  exists m'. split; [exact HS|].
  eapply eval_funcall_internal with (e := empty_env) (m1 := m) (m2 := m')
    (le2 := le') (out := Out_normal).
  - apply function_entry2_intro.
    + apply list_norepet_nil.
    + repeat constructor; simpl; intuition discriminate.
    + intros x0 y0 HX HY; cbn in HX, HY; intuition (subst; discriminate).
    + apply alloc_variables_nil.
    + reflexivity.
  - rewrite toMidstate_body. exact HE.
  - cbn. reflexivity.
  - reflexivity.
Qed.

(** The stored words are the big-endian words of the bytes. *)
Lemma tm_words_be m :
  tm_bytes_ok m -> length bytes = 32%nat -> tm_words = be_words bytes.
Proof.
  intros HB HL.
  assert (HR : forall i, (i < 32)%nat -> Int.unsigned (nth i bytes Int.zero) < 256).
  { intros i Hi. eapply load_byte_range. exact (HB i Hi). }
  apply nth_ext with (d := Int.zero) (d' := Int.zero).
  - unfold tm_words. rewrite map_length, seq_length, (be_words_length 8); [reflexivity|exact HL].
  - unfold tm_words. rewrite map_length, seq_length. intros i Hi.
    rewrite (nth_indep _ Int.zero (c_be_word bytes 0)) by (rewrite map_length, seq_length; exact Hi).
    rewrite map_nth, seq_nth by exact Hi. cbn [Nat.add].
    rewrite be_words_nth by lia. unfold c_be_word.
    apply c_be32_be32; apply HR; lia.
Qed.
