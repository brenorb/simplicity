Definition tm_call (k : nat) : statement :=
  Scall (Some (be_temp k)) (Evar _ReadBE32 (Tfunction (Tcons (tptr tuchar) Tnil) tuint cc_default))
    [Ebinop Oadd (Etempvar _hash (tptr tuchar))
       (Ebinop Omul (Econst_int (Int.repr (Z.of_nat k)) tint) (Econst_int (Int.repr 4) tint) tint)
       (tptr tuchar)].

Definition tm_assign (k : nat) : statement :=
  Sassign
    (Ederef (Ebinop Oadd (Etempvar _midstate (tptr tuint)) (Econst_int (Int.repr (Z.of_nat k)) tint)
      (tptr tuint)) tuint)
    (Etempvar (be_temp k) tuint).

Fixpoint tm_from (k n : nat) : statement :=
  match n with
  | O => Ssequence (tm_call k) (tm_assign k)
  | S n' => Ssequence (Ssequence (tm_call k) (tm_assign k)) (tm_from (S k) n')
  end.

