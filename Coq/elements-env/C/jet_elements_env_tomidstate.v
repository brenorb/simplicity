Definition tm_bytes_ok (m : mem) : Prop :=
  forall i, (i < 32)%nat ->
    Mem.load Mint8unsigned m bh (Ptrofs.unsigned oh + Z.of_nat i) = Some (Vint (nth i bytes Int.zero)).

Definition tm_words : list int := map (c_be_word bytes) (List.seq 0 8).

Lemma tm_pair_exec k le m :
  (k < 8)%nat -> tm_bytes_ok m ->
  le!_hash = Some (Vptr bh oh) -> le!_midstate = Some (Vptr bm om) ->
  Mem.valid_access m Mint32 bm (Ptrofs.unsigned om + 4 * Z.of_nat k) Writable ->
  exists m',
    Mem.store Mint32 m bm (Ptrofs.unsigned om + 4 * Z.of_nat k) (Vint (c_be_word bytes k)) = Some m' /\
    Clight2.exec_stmt sha_ge empty_env le m (Ssequence (tm_call k) (tm_assign k)) E0
      (PTree.set (be_temp k) (Vint (c_be_word bytes k)) le) m' Out_normal.
Proof.
  intros Hk HB Hhash Hmid HW.
  destruct (Mem.valid_access_store m Mint32 bm _ (Vint (c_be_word bytes k)) HW) as [m' HS].
  exists m'. split; [exact HS|].
  assert (HMul : Int.mul (Int.repr (Z.of_nat k)) (Int.repr 4) = Int.repr (4 * Z.of_nat k)).
  { unfold Int.mul. rewrite !Int.unsigned_repr by (change Int.max_unsigned with 4294967295; lia).
    f_equal. lia. }
  set (ok := Ptrofs.add oh (Ptrofs.mul (Ptrofs.repr 1) (Ptrofs.of_ints (Int.repr (4 * Z.of_nat k))))).
  assert (Hok : Ptrofs.unsigned ok = Ptrofs.unsigned oh + 4 * Z.of_nat k)
    by (apply ptr_byte_offset; lia).
  eapply exec_Sseq_1 with (t1 := E0) (t2 := E0) (m1 := m)
    (le1 := PTree.set (be_temp k) (Vint (c_be_word bytes k)) le).
  - change (PTree.set (be_temp k) (Vint (c_be_word bytes k)) le) with
      (set_opttemp (Some (be_temp k)) (Vint (c_be_word bytes k)) le).
    eapply exec_Scall with (vf := Vptr (sha_symbol_block _ReadBE32) Ptrofs.zero)
      (vargs := [Vptr bh ok]) (f := Internal f_ReadBE32).
    + reflexivity.
    + eapply eval_Elvalue; [apply eval_Evar_global; [apply PTree.gempty|exact sha_ReadBE32_symbol]|].
      apply deref_loc_reference; reflexivity.
    + eapply eval_Econs; [| |apply eval_Enil].
      * eapply eval_Ebinop; [apply eval_Etempvar; exact Hhash| |].
        -- eapply eval_Ebinop; [apply eval_Econst_int|apply eval_Econst_int|reflexivity].
        -- cbn. rewrite HMul. reflexivity.
      * reflexivity.
    + exact sha_ReadBE32_funct.
    + reflexivity.
    + unfold c_be_word. apply eval_sha_ReadBE32.
      * rewrite Hok. lia.
      * rewrite Hok. replace (Ptrofs.unsigned oh + 4 * Z.of_nat k) with
          (Ptrofs.unsigned oh + Z.of_nat (4 * k)) by lia. apply HB. lia.
      * rewrite Hok. replace (Ptrofs.unsigned oh + 4 * Z.of_nat k + 1) with
          (Ptrofs.unsigned oh + Z.of_nat (4 * k + 1)) by lia. apply HB. lia.
      * rewrite Hok. replace (Ptrofs.unsigned oh + 4 * Z.of_nat k + 2) with
          (Ptrofs.unsigned oh + Z.of_nat (4 * k + 2)) by lia. apply HB. lia.
      * rewrite Hok. replace (Ptrofs.unsigned oh + 4 * Z.of_nat k + 3) with
          (Ptrofs.unsigned oh + Z.of_nat (4 * k + 3)) by lia. apply HB. lia.
  - destruct (tm_temp_fresh k Hk) as [NH NM].
    eapply exec_Sassign with (v2 := Vint (c_be_word bytes k)) (v := Vint (c_be_word bytes k)).
    + eapply eval_Ederef. eapply eval_Ebinop;
        [apply eval_Etempvar; rewrite PTree.gso by congruence; exact Hmid
        |apply eval_Econst_int|reflexivity].
    + apply eval_Etempvar. apply PTree.gss.
    + reflexivity.
    + eapply assign_loc_value; [reflexivity|]. unfold Mem.storev.
      rewrite ptr_word_offset_from by lia. exact HS.
Qed.

