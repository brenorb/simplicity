Definition LS (m : mem) (bA : block) (cores : list ctx_core) (live : nat -> Prop) : Prop :=
  exists cs, map core_of cs = cores /\ ctxs_sep bA cs /\ ctxs_live m bA cs live.

(** Loads preserved wherever [P block lo hi] holds; permissions and
    validity never lost. *)
Definition mfrP (P : block -> Z -> Z -> Prop) (m m' : mem) : Prop :=
  (forall ch b ofs, Mem.valid_block m b -> P b ofs (ofs + size_chunk ch) ->
     Mem.load ch m' b ofs = Mem.load ch m b ofs) /\
  (forall b ofs kk p, Mem.perm m b ofs kk p -> Mem.perm m' b ofs kk p) /\
  (forall b, Mem.valid_block m b -> Mem.valid_block m' b).

Lemma mfrP_refl P m : mfrP P m m.
Proof. repeat split; auto. Qed.

Lemma mfrP_trans P m1 m2 m3 : mfrP P m1 m2 -> mfrP P m2 m3 -> mfrP P m1 m3.
Proof.
  intros (L1 & P1 & V1) (L2 & P2 & V2). split; [|split].
  - intros ch b ofs Hb Hp. rewrite L2 by (try apply V1; assumption). apply L1; assumption.
  - intros b ofs kk p Hp. apply P2, P1, Hp.
  - intros b Hb. apply V2, V1, Hb.
Qed.

Lemma mfrP_weak (P Q : block -> Z -> Z -> Prop) m m' :
  (forall b lo hi, Q b lo hi -> P b lo hi) -> mfrP P m m' -> mfrP Q m m'.
Proof.
  intros HPQ (L & Pm & V). split; [|split; assumption].
  intros ch b ofs Hb Hq. apply L; [exact Hb|apply HPQ, Hq].
Qed.

(** What one context operation leaves alone. *)
Definition opP (bA bx : block) (ob : Z) : block -> Z -> Z -> Prop :=
  fun b lo hi => b <> bx /\ (b <> bA \/ hi <= ob \/ ob + 32 <= lo).
(** What operations on contexts in [blocks], writing inside [lo0, hi0) of
    [bA], leave alone. *)
Definition rngP (bA : block) (blocks : list block) (lo0 hi0 : Z) : block -> Z -> Z -> Prop :=
  fun b lo hi => ~ In b blocks /\ (b <> bA \/ hi <= lo0 \/ hi0 <= lo).

Lemma opP_rng bA blocks lo0 hi0 bx ob m m' :
  In bx blocks -> lo0 <= ob -> ob + 32 <= hi0 -> mfrP (opP bA bx ob) m m' -> mfrP (rngP bA blocks lo0 hi0) m m'.
Proof.
  intros Hin Hlo Hhi. apply mfrP_weak. intros b lo hi (Hn & Hr). split.
  - intros ->. exact (Hn Hin).
  - destruct Hr as [Hr|Hr]; [left; exact Hr|right; lia].
Qed.

