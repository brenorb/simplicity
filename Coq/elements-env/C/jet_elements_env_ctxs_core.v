(** A change of [bA] inside [lo, hi) keeps the live contexts whose output
    fields lie outside it. *)
Lemma LS_other m m' bA cores (live : nat -> Prop) lo hi :
  LS m bA cores live ->
  (forall j cj, nth_error cores j = Some cj -> live j -> core_out cj + 32 <= lo \/ hi <= core_out cj) ->
  (forall ch b ofs, Mem.valid_block m b -> (b <> bA \/ ofs + size_chunk ch <= lo \/ hi <= ofs) ->
     Mem.load ch m' b ofs = Mem.load ch m b ofs) ->
  (forall b ofs kk p, Mem.perm m b ofs kk p -> Mem.perm m' b ofs kk p) ->
  LS m' bA cores live.
Proof.
  intros (cs & HM & HSep & HC) HR HL HP. exists cs. split; [exact HM|]. split; [exact HSep|].
  eapply live_other; [exact HC| |exact HP].
  intros j cj ch b ofs Hj Hl Hb.
  destruct (live_valid m bA cs live HC j cj Hj Hl) as (V1 & V2 & V3 & V4).
  destruct (core_nth_any cs cores j cj HM Hj) as (Hcj & _ & Ho).
  pose proof (HR j _ Hcj Hl) as Hrange. rewrite Ho in Hrange.
  destruct HSep as (NG & NM & H1 & _). destruct (H1 j cj Hj) as (D1 & _).
  destruct Hb as [->|[->|[->|[-> Hr]]]].
  - apply HL; [exact V1|left; exact D1].
  - apply HL; [exact V3|left; exact NG].
  - apply HL; [exact V4|left; exact NM].
  - apply HL; [exact V2|right]. destruct Hrange; lia.
Qed.

