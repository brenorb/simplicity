#!/usr/bin/env python3
"""Port C/jet_bitcoin_field_eval.v (struct-field evaluation, stated for
bitcoin_ge) to the SHA/environment unit's sha_ge.  Only the global
environment and the names change; the field facts at the end are replaced by
those of the structures the environment builders use.
Usage: gen-env-field-eval.py OUT   (run from Coq/)"""
import re, sys
t = open("C/jet_bitcoin_field_eval.v").read()
i = t.index("Lemma bitcoin_txEnv_tx")
t = t[:i]
assert t.count("Require Import C.jets_bitcoin C.jet_bitcoin_linkage.") == 1
t = t.replace("Require Import C.jets_bitcoin C.jet_bitcoin_linkage.", "Require Import C.jets_sha C.jet_sha_linkage.")
t = t.replace("bitcoin_ge", "sha_ge")
for old, new in (("bitcoin_field_at", "envu_field_at"), ("bitcoin_struct", "envu_struct"),
                 ("eval_bitcoin_", "eval_envu_"), ("bitcoin_ptr_add_repr", "envu_ptr_add_repr"),
                 ("bitcoin_loadv_repr", "envu_loadv_repr")):
    t = t.replace(old, new)
t = t.replace("in the Bitcoin translation\n    unit.", "in the environment\n    unit (GENERATED by bitcoin-env/gen-env-field-eval.py from\n    [jet_bitcoin_field_eval]; do not edit).")
assert "bitcoin" not in t.replace("bitcoin-env", "").replace("jet_bitcoin_field_eval", ""), re.findall(r".{20}bitcoin.{20}", t)
FIELDS = [("_sha256_midstate", [("_s", 0)]),
          ("_rawBitcoinBuffer", [("_buf", 0), ("_len", 8)]),
          ("_rawBitcoinTapEnv", [("_controlBlock", 0), ("_scriptCMR", 8), ("_pathLen", 16)]),
          ("_bitcoinTapEnv", [("_path", 0), ("_tapLeafHash", 8), ("_tappathHash", 40), ("_tapEnvHash", 72),
                              ("_internalKey", 104), ("_scriptCMR", 136), ("_pathLen", 168), ("_leafVersion", 169)])]
t += "(** Field offsets, by computation in the generated composite environment. *)\n"
t += "Definition envu_field_offset (sid field : ident) : option Z :=\n  match (Clight.genv_cenv sha_ge)!sid with\n  | Some co => match field_offset (Clight.genv_cenv sha_ge) field (co_members co) with OK (d, Full) => Some d | _ => None end\n  | None => None\n  end.\n\n"
t += "Lemma envu_field_offset_at sid field delta : envu_field_offset sid field = Some delta -> envu_field_at sid field delta.\nProof.\n  unfold envu_field_offset, envu_field_at. destruct ((Clight.genv_cenv sha_ge)!sid) as [co|]; [|discriminate].\n  destruct (field_offset (Clight.genv_cenv sha_ge) field (co_members co)) as [[d []]|]; try discriminate.\n  intros H. injection H as <-. reflexivity.\nQed.\n"
t += "\n"
for sid, fs in FIELDS:
    for f, d in fs:
        t += "Lemma envu%s%s : envu_field_at %s %s %d.\nProof. apply envu_field_offset_at. vm_compute; reflexivity. Qed.\n" % (sid, f, sid, f, d)
open(sys.argv[1], "w").write(t)
