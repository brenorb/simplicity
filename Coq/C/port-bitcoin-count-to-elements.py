#!/usr/bin/env python3
"""Port the Bitcoin-unit num_inputs/num_outputs proofs to the Elements unit.

Elements specifies the counts as [firstFail word32 (primitive
InputScriptHash)] and [firstFail word32 (primitive OutputScriptHash)]
(Programs/Transaction.hs) where Bitcoin searches InputValue/OutputValue;
the C getters are the same.  Every substitution is asserted.
Usage: port-bitcoin-count-to-elements.py OUTDIR"""
import re, sys
out = sys.argv[1]
exec(open('C/port-bitcoin-to-elements.py').read().split("for name in sys.argv")[0])

def sub(t, old, new, count):
    assert t.count(old) == count, (old, t.count(old))
    return t.replace(old, new)

for name in ['count_canonical', 'count_bridge', 'count_local']:
    t = open('C/jet_bitcoin_%s.v' % name).read()
    if name == 'count_canonical':
        t = sub(t, "Bitcoin.InputValue", "Bitcoin.InputScriptHash", 4)
        t = sub(t, "Bitcoin.OutputValue", "Bitcoin.OutputScriptHash", 4)
        t = sub(t, "(Ty.Sum Ty.Unit Word64)", "(Ty.Sum Ty.Unit Word256)", 4)
        t = sub(t, "over InputValue/OutputValue", "over InputScriptHash/OutputScriptHash", 1)
    if name == 'count_bridge':
        t = sub(t, "(fun txi => @fromZ (WordToZ 6) (Int64.signed (sigTxiValue txi)))",
                "(fun txi => from_hash256 (byteStringHash (utxoScript (sigTxiTxo txi))))", 1)
        t = sub(t, "(fun txout => @fromZ (WordToZ 6) (Int64.signed (txoValue txout)))",
                "(fun txout => from_hash256 (byteStringHash (txoScript txout)))", 1)
        t = sub(t, "Require Import Simplicity.Ty Simplicity.Word Simplicity.Primitive.Bitcoin.",
                "Require Import Simplicity.Ty Simplicity.Word Simplicity.Digest Simplicity.Primitive.Bitcoin.", 1)
    if name == 'count_local':
        t = sub(t, "OK (448, Full)", "OK (696, Full)", 1)
        t = sub(t, "OK (456, Full)", "OK (704, Full)", 1)
        t = sub(t, "bitcoin_count_env_rep 448", "bitcoin_count_env_rep 696", 1)
        t = sub(t, "bitcoin_count_env_rep 456", "bitcoin_count_env_rep 704", 1)
    t = port(t)
    t = "(** GENERATED by C/port-bitcoin-count-to-elements.py from\n    [jet_bitcoin_%s]; do not edit. *)\n" % name + t
    open('%s/jet_elements_%s.v' % (out, name), 'w').write(t)
print("ported")
