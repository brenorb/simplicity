#!/usr/bin/env python3
"""Generate C/jet_app_executable_registry.v from the coverage registry.

For every registered Bitcoin jet whose theorem is an application contract
(`application_jet_local_spec`, `application_jet_local_spec_sep`,
`application_jet_partial_spec`), emit its executability on fresh frames from
any memory representing a logical environment.  Function, environment type,
types, relation and specification are read from the registered theorem's
type; the relation's stability is found in the `env_stable` hint database.
"""
import os, re, sys

coverage, src_dir, out_path = sys.argv[1:4]
rows = [l.split() for l in open(coverage) if l.strip() and not l.startswith("#")]
cache, found, modules = {}, [], []
for fn, mod, thm in rows:
    name = mod.split(".")[1]
    if name not in cache:
        cache[name] = open(os.path.join(src_dir, name + ".v")).read()
    m = re.search(r"(?:Theorem|Lemma) %s\s*:\s*(\w+)" % re.escape(thm), cache[name])
    if m and m.group(1) in ("application_jet_local_spec", "application_jet_local_spec_sep",
                            "application_jet_partial_spec"):
        found.append((name, thm))
        if name not in modules:
            modules.append(name)
out = ['''(** GENERATED by C/gen-app-executable-registry.py; do not edit.

    Executability on fresh frames of the %d registered Bitcoin jets with an
    application contract: from any memory in which the jet's environment
    relation holds (and, for relations with a footprint, whose footprint
    blocks exist), for every input, the C function runs and leaves the
    canonical result for that logical environment in the output frame. *)
From Coq Require Import ZArith.
From compcert Require Import Integers.
Require Import C.jet_application_contract C.jet_application_sep C.jet_application_partial.
Require Import C.jet_frame_constructible_app C.jet_env_rep_stable.
''' % len(found)]
for name in modules:
    out.append("Require C.%s." % name)
out.append('''
Local Ltac bound := vm_compute; discriminate.
Local Ltac stable := eauto 8 with env_stable.
Local Ltac runs_type T :=
  lazymatch T with
  | application_jet_local_spec ?f ?ge ?E ?A ?B ?r ?s =>
      constr:(application_runs_on_fresh_frames f ge E A B r s)
  | application_jet_local_spec_sep ?f ?ge ?E ?A ?B ?r ?s =>
      constr:(application_sep_runs_on_fresh_frames f ge E A B r s)
  | application_jet_partial_spec ?f ?ge ?E ?A ?B ?r ?s =>
      constr:(application_partial_runs_on_fresh_frames f ge E A B r s)
  end.
Local Ltac run H :=
  first [eapply application_jet_local_spec_executable
        |eapply application_jet_local_spec_sep_executable
        |eapply application_jet_partial_spec_executable];
  [bound|bound|exact H|stable].
''')
for name, thm in found:
    out.append('''Theorem %s_executable :
  ltac:(let T := type of C.%s.%s in let R := runs_type T in exact R).
Proof. run C.%s.%s. Qed.
''' % (thm, name, thm, name, thm))
open(out_path, "w").write("\n".join(out))
print(len(found))
