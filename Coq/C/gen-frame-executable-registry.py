#!/usr/bin/env python3
"""Generate C/jet_frame_executable_registry.v from the coverage registry.

For every registered theorem whose statement is `jet_local_spec f A B spec`
or `memcpy_model -> jet_separated_local_spec f A B spec`, emit the
corresponding instance of `jet_runs_on_fresh_frames f A B spec` (under the
same `memcpy_model` premise where the registered theorem has it).  The
function, types and specification are taken from the registered theorem's
own type by the kernel, not restated.  Prints the module targets needed.
"""
import os, re, sys

coverage, src_dir, out_path = sys.argv[1:4]
rows = [l.split() for l in open(coverage) if l.strip() and not l.startswith("#")]
cache, plain, conditional, modules = {}, [], [], []
for fn, mod, thm in rows:
    name = mod.split(".")[1]
    if name not in cache:
        cache[name] = open(os.path.join(src_dir, name + ".v")).read()
    m = re.search(r"(?:Theorem|Lemma|Corollary) %s\s*:\s*(memcpy_model\s*->\s*)?(\w+)" % re.escape(thm), cache[name])
    if not m:
        continue
    if not m.group(1) and m.group(2) == "jet_local_spec":
        plain.append((name, thm))
    elif m.group(1) and m.group(2) == "jet_separated_local_spec":
        conditional.append((name, thm))
    else:
        continue
    if name not in modules:
        modules.append(name)
out = ['''(** GENERATED by C/gen-frame-executable-registry.py; do not edit.

    Executability on fresh frames, for every input, of each registered jet
    whose contract is frame-only (%d unconditional, %d under the explicit
    [memcpy_model] of the registered theorem).  Each statement takes the
    function, types and canonical specification from the type of the
    registered theorem it instantiates. *)
From Coq Require Import ZArith.
From compcert Require Import Integers.
Require Import C.jet_bitmachine_rep C.jet_context_separated C.jet_memcpy_model.
Require Import C.jet_frame_constructible_jets.
''' % (len(plain), len(conditional))]
for name in modules:
    out.append("Require C.%s." % name)
out.append('''
Local Ltac bound := vm_compute; discriminate.
''')
for name, thm in plain:
    out.append('''Theorem %s_executable :
  ltac:(let T := type of C.%s.%s in
        lazymatch T with jet_local_spec ?f ?A ?B ?s =>
          exact (jet_runs_on_fresh_frames f A B s) end).
Proof. apply (jet_local_spec_executable _ _ _ _ C.%s.%s); bound. Qed.
''' % (thm, name, thm, name, thm))
for name, thm in conditional:
    out.append('''Theorem %s_executable :
  ltac:(let T := type of C.%s.%s in
        lazymatch T with memcpy_model -> jet_separated_local_spec ?f ?A ?B ?s =>
          exact (memcpy_model -> jet_runs_on_fresh_frames f A B s) end).
Proof.
  intros Hmodel.
  apply (jet_separated_local_spec_executable _ _ _ _ (C.%s.%s Hmodel)); bound.
Qed.
''' % (thm, name, thm, name, thm))
open(out_path, "w").write("\n".join(out))
print(" ".join("C/%s.vo" % n for n in modules))
