Definition envu_field_offset (sid field : ident) : option Z :=
  match (Clight.genv_cenv sha_ge)!sid with
  | Some co => match field_offset (Clight.genv_cenv sha_ge) field (co_members co) with OK (d, Full) => Some d | _ => None end
  | None => None
  end.

Lemma envu_field_offset_at sid field delta : envu_field_offset sid field = Some delta -> envu_field_at sid field delta.
Proof.
  unfold envu_field_offset, envu_field_at. destruct ((Clight.genv_cenv sha_ge)!sid) as [co|]; [|discriminate].
  destruct (field_offset (Clight.genv_cenv sha_ge) field (co_members co)) as [[d []]|]; try discriminate.
  intros H. injection H as <-. reflexivity.
Qed.

