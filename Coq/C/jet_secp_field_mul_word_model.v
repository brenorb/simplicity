Lemma range_shr l h k : 0 <= k ->
  0 <= (Int64.unsigned h * 2 ^ 64 + Int64.unsigned l) / 2 ^ k < 2 ^ 128.
Proof.
  intros Hk. pose proof (Int64.unsigned_range l). pose proof (Int64.unsigned_range h).
  change Int64.modulus with (2 ^ 64) in *.
  assert (1 <= 2 ^ k) by (change 1 with (2 ^ 0); apply Z.pow_le_mono_r; lia).
  split; [apply Z.div_pos; lia|].
  apply Z.le_lt_trans with (Int64.unsigned h * 2 ^ 64 + Int64.unsigned l); [|lia].
  apply Z.div_le_upper_bound; nia.
Qed.
