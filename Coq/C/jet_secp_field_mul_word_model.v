Definition fm_lo (W : Z) : int64 := Int64.repr (W mod 2 ^ 64).
Definition fm_hi (W : Z) : int64 := Int64.repr (W / 2 ^ 64).

Lemma uns_fm_lo W : Int64.unsigned (fm_lo W) = W mod 2 ^ 64.
Proof. unfold fm_lo. rewrite Int64.unsigned_repr_eq. apply Z.mod_mod. lia. Qed.
Lemma uns_fm_hi W : 0 <= W < 2 ^ 128 -> Int64.unsigned (fm_hi W) = W / 2 ^ 64.
Proof.
  intros HW. unfold fm_hi. apply Int64.unsigned_repr.
  change Int64.max_unsigned with (2 ^ 64 - 1).
  split; [apply Z.div_pos; lia|]. apply Z.lt_le_pred. apply Z.div_lt_upper_bound; lia.
Qed.
Lemma fm_join W : 0 <= W < 2 ^ 128 ->
  Int64.unsigned (fm_hi W) * 2 ^ 64 + Int64.unsigned (fm_lo W) = W.
Proof.
  intros HW. rewrite uns_fm_hi, uns_fm_lo by exact HW.
  pose proof (Z.div_mod W (2 ^ 64) ltac:(lia)). lia.
Qed.

Lemma evok_intro rho tag base args W :
  rho base = fm_lo W -> rho (S base) = fm_hi W ->
  u128_sem tag (map (uv rho) args) = Some W -> 0 <= W < 2 ^ 128 ->
  u128_evok rho (mkev tag base 2 args).
Proof.
  intros HL HH HS HR. split; [reflexivity|]. exists W. cbn [etag eargs ebase].
  split; [exact HS|]. split; [exact HR|].
  rewrite HL, HH, uns_fm_lo, uns_fm_hi by exact HR. split; reflexivity.
Qed.

