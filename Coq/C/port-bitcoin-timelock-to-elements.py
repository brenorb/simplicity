#!/usr/bin/env python3
"""Port the Bitcoin-unit lock-time proofs to the Elements unit.

The Elements programs txIsFinal, txLockHeight, txLockTime, checkLockHeight
and checkLockTime (Programs/TimeLock.hs) and the C jets are textually those
of Bitcoin; only the transaction layout differs (isFinal at 752, lockTime
at 728).  Each layout substitution is asserted.
Usage: port-bitcoin-timelock-to-elements.py OUTDIR"""
import os, re, sys
out = sys.argv[1]
exec(open('C/port-bitcoin-to-elements.py').read().split("for name in sys.argv")[0])

def emit(name, text):
    text = "(** GENERATED by C/port-bitcoin-timelock-to-elements.py from\n    [jet_bitcoin_%s]; do not edit. *)\n" % name + text
    open('%s/jet_elements_%s.v' % (out, name), 'w').write(text)

def layout(t):
    t = re.sub(r"\b480\b", "752", t)
    t = re.sub(r"\b481\b", "753", t)
    return t

# the two statement helpers of fee_local that the lock proofs use
fee = open('C/jet_bitcoin_fee_local.v').read()
i = fee.index("Definition bitcoin_fee_mid"); j = fee.index("Lemma exec_bitcoin_env_tx_set")
k = fee.index("Definition bitcoin_fee_temps")
assert i < j < k
sub = fee[:i] + fee[j:k]
assert sub.count("480") == 1 and "0 <= delta <= 480" in sub   # last 8-byte slot of the record
for line in ["Require Import C.jet_bitcoin_totals_spec C.jet_bitcoin_totals_canonical C.jet_bitcoin_totals_local.\n",
             "Require Import C.jet_bitcoin_fee_spec.\n"]:
    assert sub.count(line) == 1, line
    sub = sub.replace(line, "")
emit('fee_local', layout(port(sub)).replace("jet_elements_fee_local", "jet_elements_tx_field_set"))

# the semantic helpers of distance_spec that check_lock uses (pair, core programs)
dist = open('C/jet_bitcoin_distance_spec.v').read()
h = dist.index("Definition word16_zero"); a0 = dist.index("Lemma core_reader_sem"); b0 = dist.index("Definition bitcoin_version_prim")
assert h < a0 < b0
c0 = dist.index("(**"); c1 = dist.index("*)", c0) + 2
assert c0 == 0
helper_doc = "(** Semantics of pairing and of core programs in the Elements primitive\n    reader monad (the generic part of the Bitcoin distance specification\n    module; no Elements program is defined here). *)"
emit('distance_spec', helper_doc + port(dist[c1:h] + dist[a0:b0]))
import os
os.rename(out + '/jet_elements_fee_local.v', out + '/jet_elements_tx_field_set.v')
os.rename(out + '/jet_elements_distance_spec.v', out + '/jet_elements_prim_sem.v')

for name in ['is_final_spec', 'is_final_local', 'lock_spec', 'lock_exec', 'lock_local', 'bool_wrapper', 'check_lock']:
    src = open('C/jet_bitcoin_%s.v' % name).read()
    t = layout(port(src)).replace("C.jet_elements_fee_local", "C.jet_elements_tx_field_set").replace("C.jet_elements_distance_spec", "C.jet_elements_prim_sem")
    emit(name, t)
print("ported")
