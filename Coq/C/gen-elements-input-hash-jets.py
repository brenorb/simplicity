#!/usr/bin/env python3
"""Generate C/jet_elements_input_hash_jets.v by instantiating the
output_script_hash proof block of C/jet_elements_indexed_ptr_jets.v for the
per-input 256-bit fields.  Every textual substitution is asserted to apply.
Usage: gen-elements-input-hash-jets.py C/jet_elements_indexed_ptr_jets.v OUT"""
import sys

src, out_path = sys.argv[1:3]
s = open(src).read()
head = s[:s.index("Local Transparent Archi.ptr64.")]
head = head[head.index("From Coq"):]
blk = s[s.index("(** * output_script_hash *)"):s.index("(** * input_prev_outpoint *)")]

def sub(t, old, new):
    assert old in t, old
    return t.replace(old, new)

def base(name, prim, words, bytes_of):
    t = sub(blk, "output_script_hash", name)
    t = sub(t, "Elements.OutputScriptHash", "Elements." + prim)
    t = sub(t, "script_hash_words (txo : txOutput)", "%s (txo : sigTxInput)" % words)
    t = t.replace("script_hash_words txo", words + " txo").replace("script_hash_words x", words + " x")
    t = t.replace("unfold script_hash_words", "unfold " + words)
    assert "script_hash_words" not in t.replace(words, "")
    t = sub(t, "(txoScript txo)", "(%s txo)" % bytes_of)
    t = sub(t, "(txoScript x)", "(%s x)" % bytes_of)
    t = sub(t, "elements_elementsTransaction_numOutputs", "elements_elementsTransaction_numInputs")
    t = sub(t, "elements_elementsTransaction_output", "elements_elementsTransaction_input")
    t = sub(t, "elements_sizeof_sigOutput", "elements_sizeof_sigInput")
    t = sub(t, "sigTxOut", "sigTxIn")
    t = sub(t, "_numOutputs", "_numInputs")
    t = sub(t, "_output ", "_input ")
    t = sub(t, "_sigOutput", "_sigInput")
    return t

def direct(name, prim, words, bytes_of, field, off, lemma):
    t = base(name, prim, words, bytes_of)
    t = sub(t, "_scriptPubKey", field)
    t = sub(t, "248 180 8 704", "544 %d 0 696" % off)
    t = sub(t, "704 8 248 180 32", "696 0 544 %d 32" % off)
    t = sub(t, "_sigInput 248 %s 180" % field, "_sigInput 544 %s %d" % (field, off))
    assert lemma in t, lemma  # the field renaming above yields the field lemma's name
    return t

def nested(name, prim, words, bytes_of, f1, d1, sid1, lemma1, f2, d2, lemma2):
    t = base(name, prim, words, bytes_of)
    t = sub(t, """(Tstruct _sigInput noattr))) (Tstruct _sigInput noattr)) _scriptPubKey
    (Tstruct _sha256_midstate noattr))""",
            """(Tstruct _sigInput noattr))) (Tstruct _sigInput noattr)) %s (Tstruct %s noattr))
    %s (Tstruct _sha256_midstate noattr))""" % (f1, sid1, f2))
    t = sub(t, "Eaddrof (Efield (Ederef", "Eaddrof (Efield (Efield (Ederef")
    t = sub(t, "248 180 8 704", "544 %d 0 696" % (d1 + d2))
    t = sub(t, "704 8 248 180 32", "696 0 544 %d 32" % (d1 + d2))
    i = t.index("    exact (eval_elements_elem_field_addr")
    j = t.index("  - intros a environment.")
    t = t[:i] + """    pose proof (eval_elements_elem_nested_field_addr e le' m' _t'4 _i _sigInput 544 %s %d %s
      %s %d _sha256_midstate bin inbase r elements_sizeof_sigInput %s
      %s H4 HI Hi0 ltac:(split; lia) ltac:(lia) ltac:(lia)
      ltac:(clear - HM; lia) ltac:(clear - HM; lia)) as H.
    exact H.
""" % (f1, d1, sid1, f2, d2, lemma1, lemma2) + t[j:]
    return t

out = '''(** GENERATED by C/gen-elements-input-hash-jets.py from the
    output_script_hash proof of [jet_elements_indexed_ptr_jets]; do not edit.

    Elements per-input hash getters of the shape
      [i = read32(&src); if (writeBit(dst, i < numInputs)) writeHash(dst, &input[i].FIELD); else skipBits(dst, 256)]
    against the corresponding primitives.  The element relation states that
    the C field holds the hash the primitive denotes (SHA-256 of the logical
    byte string): an initial representation requirement on the environment. *)
''' + head + '''Require Import C.jet_elements_indexed_ptr_jets.
Local Transparent Archi.ptr64.
Local Opaque elements_ge ge0.
Set Default Timeout 60.

(** [&(xp[i]).f1.f2] where [f1] and [f2] are struct-valued fields. *)
Lemma eval_elements_elem_nested_field_addr e le m t4 ip sid sz f1 d1 sid1 f2 d2 sid2 b inbase r :
  sizeof (Clight.genv_cenv elements_ge) (Tstruct sid noattr) = sz ->
  elements_field_at sid f1 d1 -> elements_field_at sid1 f2 d2 ->
  le!t4 = Some (Vptr b (Ptrofs.repr inbase)) -> le!ip = Some (Vlong r) ->
  0 <= inbase -> 0 < sz <= 1000 -> 0 <= d1 -> 0 <= d2 ->
  inbase + sz * Int64.unsigned r + d1 + d2 <= Ptrofs.max_unsigned ->
  inbase + sz * Int64.unsigned r + 1 <= Ptrofs.max_unsigned ->
  eval_expr elements_ge e le m
    (Eaddrof (Efield (Efield (Ederef (Ebinop Oadd (Etempvar t4 (tptr (Tstruct sid noattr))) (Etempvar ip tulong)
      (tptr (Tstruct sid noattr))) (Tstruct sid noattr)) f1 (Tstruct sid1 noattr)) f2 (Tstruct sid2 noattr))
      (tptr (Tstruct sid2 noattr)))
    (Vptr b (Ptrofs.repr (inbase + sz * Int64.unsigned r + (d1 + d2)))).
Proof.
  intros Hsz HF1 HF2 H4 HI HB HS Hd1 Hd2 HM HM1.
  assert (HR : 0 <= Int64.unsigned r) by (apply Int64.unsigned_range).
  assert (HI' : le!ip = Some (Vlong (Int64.repr (Int64.unsigned r)))) by (rewrite Int64.repr_unsigned; exact HI).
  assert (Hsr : 0 <= sz * Int64.unsigned r) by (apply Z.mul_nonneg_nonneg; [lia|exact HR]).
  pose proof (eval_elements_index e le m t4 ip sid sz b inbase (Int64.unsigned r) Hsz H4 HI' HB HS HR
    ltac:(clear - HM1 Hsr; lia)) as HElem.
  eapply eval_Eaddrof.
  assert (Hr : Ptrofs.repr (inbase + sz * Int64.unsigned r + (d1 + d2)) =
    Ptrofs.add (Ptrofs.add (Ptrofs.repr (inbase + sz * Int64.unsigned r)) (Ptrofs.repr d1)) (Ptrofs.repr d2)).
  { rewrite elements_ptr_add_repr by (clear - HM Hd1 Hd2 Hsr HB; lia).
    rewrite elements_ptr_add_repr by (clear - HM Hd1 Hd2 Hsr HB; lia).
    apply (f_equal Ptrofs.repr). lia. }
  rewrite Hr.
  eapply eval_elements_field_lvalue; [reflexivity|exact HF2|].
  eapply eval_elements_field_struct; [reflexivity|exact HF1|exact HElem].
Qed.

(** Byte strings hashed by the canonical semantics. *)
Definition utxo_script_bytes (txi : sigTxInput) : list Integers.byte := utxoScript (sigTxiTxo txi).

(** [view (to sigTxiIssuance . just_ . to issuanceAmount . under amount . prf_)]:
    the range-proof bytes of the issuance amount (respectively token amount)
    when the input has an issuance with a confidential amount, else empty. *)
Definition issuance_asset_proof_bytes (txi : sigTxInput) : list Integers.byte :=
  match sigTxiIssuance txi with
  | Some i => viewPrf (match i with inl new => newIssuanceAmount new | inr re => reissuanceAmount re end)
  | None => nil
  end.

Definition issuance_token_proof_bytes (txi : sigTxInput) : list Integers.byte :=
  match sigTxiIssuance txi with
  | Some i => viewPrf (match i with
                       | inl new => newIssuanceTokenAmount new
                       | inr _ => Explicit Int64.zero
                       end)
  | None => nil
  end.

Lemma elements_sigInput_issuance : elements_field_at _sigInput _issuance 256.
Proof. vm_compute; reflexivity. Qed.
Lemma elements_assetIssuance_assetRangeProofHash :
  elements_field_at _assetIssuance _assetRangeProofHash 104.
Proof. vm_compute; reflexivity. Qed.
Lemma elements_assetIssuance_tokenRangeProofHash :
  elements_field_at _assetIssuance _tokenRangeProofHash 136.
Proof. vm_compute; reflexivity. Qed.

'''
out += direct("input_script_sig_hash", "InputScriptSigHash", "script_sig_hash_words",
              "sigTxiScriptSig", "_scriptSigHash", 64, "elements_sigInput_scriptSigHash")
out += "\n" + nested("input_script_hash", "InputScriptHash", "utxo_script_hash_words",
                     "utxo_script_bytes", "_txo", 136, "_utxo", "elements_sigInput_txo",
                     "_scriptPubKey", 0, "elements_utxo_scriptPubKey")
out += "\n" + nested("issuance_asset_proof", "IssuanceAssetProof", "issuance_asset_proof_words",
                     "issuance_asset_proof_bytes", "_issuance", 256, "_assetIssuance",
                     "elements_sigInput_issuance", "_assetRangeProofHash", 104,
                     "elements_assetIssuance_assetRangeProofHash")
out += "\n" + nested("issuance_token_proof", "IssuanceTokenProof", "issuance_token_proof_words",
                     "issuance_token_proof_bytes", "_issuance", 256, "_assetIssuance",
                     "elements_sigInput_issuance", "_tokenRangeProofHash", 136,
                     "elements_assetIssuance_tokenRangeProofHash")
open(out_path, "w").write(out)
