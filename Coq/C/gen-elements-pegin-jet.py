#!/usr/bin/env python3
"""Generate C/jet_elements_pegin_local.v from C/jet_elements_annex_local.v.

simplicity_input_pegin has the body of simplicity_input_annex_hash with the
flag field isPegin (offset 537) and the hash field pegin (offset 32 of the
input record) instead of hasAnnex (536) and annexHash (0).  The proof is the
annex proof with those names and offsets; each substitution is asserted.
Usage: gen-elements-pegin-jet.py C/jet_elements_annex_local.v OUT"""
import re, sys

src, out_path = sys.argv[1:3]
t = open(src).read()

def sub(old, new, count=None):
    global t
    n = t.count(old)
    assert n >= 1 and (count is None or n == count), (old, n)
    t = t.replace(old, new)

sub("Lemma elements_sigInput_annexHash : elements_field_at _sigInput _annexHash 0.", "Lemma elements_sigInput_pegin_local : elements_field_at _sigInput _pegin 32.", 1)
sub("_hasAnnex", "_isPegin")
sub("elements_sigInput_annexHash", "elements_sigInput_pegin")
sub("_annexHash 0 _sha256_midstate", "_pegin 32 _sha256_midstate", 1)
sub("_annexHash", "_pegin")
sub("Elements.InputAnnexHash", "Elements.InputPegin")
sub("f_simplicity_input_annex_hash", "f_simplicity_input_pegin")
sub("map (fun txi => option_map byteStringHash (sigTxiAnnex txi)) (sigTxIn (Elements.envTx e))",
    "map sigTxiPegin (sigTxIn (Elements.envTx e))", 1)
sub("destruct (sigTxiAnnex txi); reflexivity.", "destruct (sigTxiPegin txi); reflexivity.", 1)
t = re.sub(r"\b536\b", "537", t)
# the hash sits 32 bytes into the element
sub("forall h, o = Some h -> hash_elem_rep m b ofs h.", "forall h, o = Some h -> hash_elem_rep m b (ofs + 32) h.", 1)
sub("assert (Hrep : hash_elem_rep m bin eofs h)", "assert (Hrep : hash_elem_rep m bin (eofs + 32) h)", 1)
sub("assert (Hrep2 : hash_elem_rep mb2 bin eofs h).", "assert (Hrep2 : hash_elem_rep mb2 bin (eofs + 32) h).", 1)
sub("256 bin eofs (eofs + 32)).", "256 bin (eofs + 32) (eofs + 32 + 32)).", 1)
sub("(hash_elem_pay bd dbase bw outedge mb2 bin eofs h", "(hash_elem_pay bd dbase bw outedge mb2 bin (eofs + 32) h", 1)
sub("f_writeHash eofs", "f_writeHash (eofs + 32)", 1)
sub("                  eofs ltac:(unfold eofs; lia))", "                  (eofs + 32) ltac:(unfold eofs; lia))", 1)
t = t.replace("annex", "pegin").replace("Annex", "Pegin")
t = re.sub(r"\(\*\*.*?\*\)\n", """(** GENERATED by C/gen-elements-pegin-jet.py from [jet_elements_annex_local];
    do not edit.  Actual Elements input_pegin jet against primitive
    InputPegin: the annex proof with flag field [isPegin] and hash field
    [pegin] (32 bytes into the input record). *)
""", t, count=1, flags=re.S)
open(out_path, "w").write(t)
