#!/usr/bin/env python3
"""Port SHA-unit jet proofs whose C function is textually identical in the
Elements unit (up to the function's name) and whose canonical specification
is the same program.  Each substitution is asserted; the Clight identity is
checked against the two generated programs.

Usage: gen-elements-sha-ports.py OUTDIR   (run from Coq/)"""
import re, sys
out = sys.argv[1]

def fundef(path, name):
    m = re.search(r"^Definition %s := (.*?)\n\|\}\.\n" % name, open(path).read(), re.S | re.M)
    return m.group(1)

# (source module, SHA-unit function, Elements function, theorem, new theorem)
PORTS = [("jet_bitcoin_annex_hash_jet", "f_simplicity_bitcoin_annex_hash", "f_simplicity_annex_hash",
          "bitcoin_annex_hash_local_spec", "elements_annex_hash_local_spec", "jet_elements_annex_hash_jet")]
for mod, fsha, felt, thm, newthm, newmod in PORTS:
    if fundef("C/jets_sha.v", fsha) != fundef("C/jets_elements.v", felt):
        sys.exit("%s and %s differ" % (fsha, felt))
    text = open("C/%s.v" % mod).read()
    assert text.count(thm) == 1 and fsha in text
    others = set(re.findall(r"[A-Za-z_0-9]*bitcoin[A-Za-z_0-9]*", text)) - {fsha, thm, "C.jet_bitcoin_ctx_hash_spec", "jet_bitcoin_ctx_hash_spec"}
    if others:
        sys.exit("%s: unexpected Bitcoin-specific names %s" % (mod, sorted(others)))
    text = text.replace(fsha, felt).replace(thm, newthm)
    text = ("(** GENERATED by elements-sha/gen-elements-sha-ports.py from [%s]; do not edit.\n"
            "    The Elements function [%s] has the Clight text of the SHA unit's [%s]\n"
            "    and the same canonical specification. *)\n" % (mod, felt, fsha)) + text
    open("%s/%s.v" % (out, newmod), "w").write(text)
    print("ported", newmod)
