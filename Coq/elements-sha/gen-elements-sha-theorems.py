#!/usr/bin/env python3
"""Generate elements-sha/C/jet_elements_sha_jets.v.

In the derived tree the accepted SHA jet theorems are compiled against the
Elements program.  This module restates each of them explicitly for
[elements_ge] and the function of [C.jets_elements]: the contract
definitions are copied with [sha_ge] replaced by [elements_ge], and each
theorem is the accepted one transported along [sha_ge = elements_ge].
Statements are copied verbatim.  Usage: gen-elements-sha-theorems.py C OUT"""
import re, sys

src_dir, out_path = sys.argv[1:3]
CONTRACTS = {"sha_jet_local_spec": "jet_sha_block_local",
             "sha_jet_local_spec_pre": None, "sha_jet_partial_local_spec": None}
MODULES = [("jet_sha_block_local", 1, False), ("jet_sha_ctx8_add_jets", 10, True),
           ("jet_sha_ctx8_add_buffer_jet", 1, True), ("jet_sha_ctx8_finalize_jet", 1, True),
           ("jet_sha_tapdata_jet", 1, True)]
IMPORT = re.compile(r"^(From|Require|Import|Local Open Scope|Open Scope|Local Transparent)\b")
import glob
texts = {p: open(p).read() for p in glob.glob(src_dir + "/jet_sha*.v")}
defs = []
for name in CONTRACTS:
    hits = [(p, m) for p, t in texts.items()
            for m in re.finditer(r"^Definition %s (.*?) : Prop :=\n(.*?)\.\n\n" % name, t, re.S | re.M)]
    if len(hits) != 1:
        sys.exit("%s: expected one definition, found %d" % (name, len(hits)))
    params, body = hits[0][1].groups()
    if body.count("sha_ge") != 1:
        sys.exit("%s: expected exactly one occurrence of sha_ge" % name)
    args = " ".join(re.findall(r"\((\w+(?: \w+)*) :", params))
    defs.append((name, params, body.replace("sha_ge", "elements_ge"), args))
requires, others, theorems = [], [], []
for mod, expected, conditional in MODULES:
    text = texts["%s/%s.v" % (src_dir, mod)]
    first = re.search(r"^(Theorem|Lemma|Definition|Section|Fixpoint|Ltac|Inductive|Record|Notation|Local Notation)\b", text, re.M)
    head = re.sub(r"\(\*.*?\*\)", "", text[:first.start()], flags=re.S)
    for s in [x.strip() + "." for x in re.split(r"\.\s*\n", head) if x.strip()]:
        if IMPORT.match(s):
            target = requires if s.startswith(("From", "Require")) else others
            if s not in target:
                target.append(s)
    requires.append("Require Import C.%s." % mod)
    if conditional:
        found = re.findall(r"^Theorem (\w+_local_spec) : memcpy_model ->\n(.*?)\.\nProof\.", text, re.S | re.M)
    else:
        found = re.findall(r"^Theorem (\w+_local_spec) :\n(.*?)\.\nProof\.", text, re.S | re.M)
    if len(found) != expected:
        sys.exit("%s: expected %d jet theorems, found %d" % (mod, expected, len(found)))
    for name, stmt in found:
        m = re.match(r"\s*(sha_jet_\w+)(.*)$", stmt, re.S)
        contract, rest = m.group(1), m.group(2)
        if contract not in CONTRACTS:
            sys.exit("%s: unknown contract %s" % (name, contract))
        fs = re.findall(r"\bf_simplicity_\w+|\bf_\w+", rest)
        if len(fs) != 1:
            sys.exit("%s: expected one function in the statement" % name)
        rest2 = rest.replace(fs[0], "jets_elements." + fs[0])
        prem = "memcpy_model ->\n" if conditional else "\n"
        proof = ("Proof. intro H. apply %s_to_elements. exact (%s H). Qed.\n" % (contract, name) if conditional
                 else "Proof. apply %s_to_elements. exact %s. Qed.\n" % (contract, name))
        theorems.append("Theorem %s_elements : %s  %s_elements%s.\n%s" % (name, prem, contract, rest2, proof))
out = ['''(** GENERATED by elements-sha/gen-elements-sha-theorems.py; do not edit.

    The accepted SHA jet theorems for the Elements translation unit: the
    functions are those of [C.jets_elements] and the executions are in
    [elements_ge].  The premises about global objects are the accepted ones
    ([sha_dispatch_ok] etc.), read in the Elements program. *)''']
out += requires
out.append("Require C.jets_elements.")
out.append("Require Import C.jet_elements_linkage C.jet_elements_sha_program.")
out += others
out.append("")
for name, params, body, args in defs:
    out.append("Definition %s_elements %s : Prop :=\n%s.\n" % (name, params, body))
    out.append("Lemma %s_to_elements %s :\n  %s %s -> %s_elements %s.\n"
               "Proof. unfold %s, %s_elements. rewrite <- elements_sha_genv. exact (fun H => H). Qed.\n"
               % (name, params, name, args, name, args, name, name))
out += theorems
open(out_path, "w").write("\n".join(out))
print("%d contracts, %d theorems" % (len(defs), len(theorems)))
