#!/usr/bin/env python3
"""Port the SHA-unit proofs of build_tapleaf_simplicity and build_tapbranch
to the Elements unit.  The Elements C functions and canonical programs have
the same shape as Bitcoin's; only the tag strings differ ("TapLeaf/elements",
"TapBranch/elements").  The tag constants are recomputed here and re-checked
by Coq ([*_tag_hash_eval], [*_prefix_eval], [*_tag_block_bytes] are proved
by evaluation in the generated modules).  Every definition of the ported
modules is renamed with the prefix [el_] so that the Bitcoin modules, which
are still imported for their tag-independent lemmas' dependencies, cannot be
confused with the ports.

Usage: gen-elements-tap-ports.py OUTDIR   (run from Coq/)"""
import hashlib, re, struct, sys
out = sys.argv[1]

K = [0x428a2f98,0x71374491,0xb5c0fbcf,0xe9b5dba5,0x3956c25b,0x59f111f1,0x923f82a4,0xab1c5ed5,0xd807aa98,0x12835b01,0x243185be,0x550c7dc3,0x72be5d74,0x80deb1fe,0x9bdc06a7,0xc19bf174,0xe49b69c1,0xefbe4786,0x0fc19dc6,0x240ca1cc,0x2de92c6f,0x4a7484aa,0x5cb0a9dc,0x76f988da,0x983e5152,0xa831c66d,0xb00327c8,0xbf597fc7,0xc6e00bf3,0xd5a79147,0x06ca6351,0x14292967,0x27b70a85,0x2e1b2138,0x4d2c6dfc,0x53380d13,0x650a7354,0x766a0abb,0x81c2c92e,0x92722c85,0xa2bfe8a1,0xa81a664b,0xc24b8b70,0xc76c51a3,0xd192e819,0xd6990624,0xf40e3585,0x106aa070,0x19a4c116,0x1e376c08,0x2748774c,0x34b0bcb5,0x391c0cb3,0x4ed8aa4a,0x5b9cca4f,0x682e6ff3,0x748f82ee,0x78a5636f,0x84c87814,0x8cc70208,0x90befffa,0xa4506ceb,0xbef9a3f7,0xc67178f2]
IV = [0x6a09e667,0xbb67ae85,0x3c6ef372,0xa54ff53a,0x510e527f,0x9b05688c,0x1f83d9ab,0x5be0cd19]
M = 0xffffffff
def rotr(x, n): return ((x >> n) | (x << (32 - n))) & M
def compress(h, block):
    w = list(struct.unpack(">16I", block))
    for i in range(16, 64):
        s0 = rotr(w[i-15],7) ^ rotr(w[i-15],18) ^ (w[i-15] >> 3)
        s1 = rotr(w[i-2],17) ^ rotr(w[i-2],19) ^ (w[i-2] >> 10)
        w.append((w[i-16] + s0 + w[i-7] + s1) & M)
    a,b,c,d,e,f,g,hh = h
    for i in range(64):
        t1 = (hh + (rotr(e,6)^rotr(e,11)^rotr(e,25)) + ((e&f)^(~e&g)) + K[i] + w[i]) & M
        t2 = ((rotr(a,2)^rotr(a,13)^rotr(a,22)) + ((a&b)^(a&c)^(b&c))) & M
        a,b,c,d,e,f,g,hh = (t1+t2)&M,a,b,c,(d+t1)&M,e,f,g
    return [(x+y)&M for x,y in zip(h,[a,b,c,d,e,f,g,hh])]
def consts(tag):
    block = tag + b"\x80" + b"\0" * (55 - len(tag)) + struct.pack(">Q", 8 * len(tag))
    word = hashlib.sha256(tag).digest()
    assert struct.pack(">8I", *compress(IV, block)) == word
    prefix = struct.pack(">8I", *compress(IV, word + word))
    return dict(prefix=int.from_bytes(prefix, "big"), word=int.from_bytes(word, "big"),
                block=int.from_bytes(block, "big"), ints="[%s]" % "; ".join(str(c) for c in tag), n=len(tag))

def num(text, name):
    return int(re.search(r"Definition %s :[^=]*:=\s*@fromZ \(WordToZ \d\) (\d+)\." % name, text).group(1))
def ints(text, name):
    return re.search(r"Definition %s : list int := map Int.repr (\[[0-9; ]*\])\." % name, text).group(1)

leaf_src = open("C/jet_bitcoin_tapleaf_hash_spec.v").read()
branch_src = open("C/jet_bitcoin_build_tapbranch_spec.v").read()
# the recomputation reproduces the accepted Bitcoin constants
for src, nm, tag in ((leaf_src, "tapleaf", b"TapLeaf"), (branch_src, "tapbranch", b"TapBranch")):
    c = consts(tag)
    assert (num(src, nm + "_prefix"), num(src, nm + "_tag_word"), num(src, nm + "_tag_block"), ints(src, nm + "_tag_bytes")) == \
           (c["prefix"], c["word"], c["block"], c["ints"]), nm
LEAF, BRANCH = consts(b"TapLeaf/elements"), consts(b"TapBranch/elements")
BLEAF, BBRANCH = consts(b"TapLeaf"), consts(b"TapBranch")

tags = '''(** GENERATED by elements-sha/gen-elements-tap-ports.py; do not edit.
    The "TapLeaf/elements" tag of Programs.Elements.buildTapleafSimplicity:
      tapleafPrefix = scribe . toWord256 . integerHash256 . ivHash . tagIv $ fromString "TapLeaf/elements"
    Each constant is checked by evaluation of the canonical [hashBlock]. *)
From Coq Require Import ZArith List.
From compcert Require Import Integers.
Require sha.SHA256.
Require Import Simplicity.Ty Simplicity.Word.
Require Simplicity.Alg Simplicity.SHA256.
Require Import C.jet_spec C.jet_buffer_empty_spec C.jet_buffer_input C.jet_sha256_ctx8_init_spec.
Require Import C.jet_sha256_iv_init C.jet_read8s_layout C.jet_word32_chunks.
Require Import C.jet_sha_ctx8_spec C.jet_sha_ctx8_model C.jet_sha_finalize_exec C.jet_sha_finalize_spec.
Require Import C.jet_sha_tapdata_spec C.jet_sha_hash_closed.
Import ListNotations.
Local Open Scope Z_scope.

Definition el_tapleaf_prefix : Ty.tySem (Word 8) :=
  @fromZ (WordToZ 8) %(prefix)d.
Definition el_tapleaf_tag_word : Ty.tySem (Word 8) :=
  @fromZ (WordToZ 8) %(word)d.
Definition el_tapleaf_tag_block : Ty.tySem (Word 9) :=
  @fromZ (WordToZ 9) %(block)d.
Definition el_tapleaf_tag_bytes : list int := map Int.repr %(ints)s.

Lemma el_tapleaf_tag_hash_eval :
  @Simplicity.SHA256.hashBlock Alg.CoreFunSem (iv_word, el_tapleaf_tag_block) = el_tapleaf_tag_word.
Proof. vm_compute. reflexivity. Qed.

Lemma el_tapleaf_prefix_eval :
  @Simplicity.SHA256.hashBlock Alg.CoreFunSem (iv_word, (el_tapleaf_tag_word, el_tapleaf_tag_word)) = el_tapleaf_prefix.
Proof. vm_compute. reflexivity. Qed.

Lemma el_tapleaf_tag_block_bytes :
  map Int.unsigned (map word8_array_value (vector_values (Word 3) 6 el_tapleaf_tag_block)) =
  map Int.unsigned (el_tapleaf_tag_bytes ++ sha_pad (Int64.repr %(n)d)).
Proof. vm_compute. reflexivity. Qed.
''' % LEAF
open(out + "/jet_elements_tap_tags.v", "w").write(tags)

MODS = ["build_tapleaf_spec", "make_tapleaf_exec", "build_tapleaf_jet",
        "build_tapbranch_spec", "make_tapbranch_exec", "build_tapbranch_jet"]
texts = {m: open("C/jet_bitcoin_%s.v" % m).read() for m in MODS}
defined = set()
for t in texts.values():
    defined |= set(re.findall(r"^(?:Local |Global )?(?:Definition|Lemma|Theorem|Fixpoint|Ltac|Corollary|Remark|Fact|Example|Inductive|Record)\s+([A-Za-z_][A-Za-z_0-9']*)", t, re.M))
defined |= {"tapleaf_prefix", "tapleaf_tag_word", "tapleaf_tag_block", "tapleaf_tag_bytes",
            "tapleaf_tag_hash_eval", "tapleaf_prefix_eval", "tapleaf_tag_block_bytes"}
assert not any(d.startswith("el_") for d in defined)
rename = re.compile(r"(?<![A-Za-z_0-9'.])(%s)(?![A-Za-z_0-9'])" % "|".join(sorted(map(re.escape, defined), key=len, reverse=True)))

def sub1(text, old, new, count=None):
    n = text.count(old)
    assert n >= 1 if count is None else n == count, (old, n)
    return text.replace(old, new)

for m, t in texts.items():
    leaf = "tapleaf" in m
    B, E = (BLEAF, LEAF) if leaf else (BBRANCH, BRANCH)
    # C identifiers of the Elements unit
    for old, new in (("f_simplicity_bitcoin_build_tapleaf_simplicity", "f_simplicity_build_tapleaf_simplicity"),
                     ("f_simplicity_bitcoin_build_tapbranch", "f_simplicity_build_tapbranch"),
                     ("_simplicity_bitcoin_make_tapleaf", "_simplicity_make_tapleaf"),
                     ("_simplicity_bitcoin_make_tapbranch", "_simplicity_make_tapbranch")):
        t = t.replace(old, new)
    # the tag: its bytes, its length, and (for the branch) the constants defined in the spec module
    if B["ints"] in t:
        t = t.replace(B["ints"], E["ints"])
    if "_exec" in m:
        t = sub1(t, "(i < %d)%%nat" % B["n"], "(i < %d)%%nat" % E["n"], 1)
    if m != "build_tapleaf_spec":
        t = t.replace("Int64.repr %d)" % B["n"], "Int64.repr %d)" % E["n"])
    if m == "build_tapbranch_spec":
        for k in ("prefix", "word", "block"):
            t = sub1(t, str(B[k]), str(E[k]), 1)
    assert "bitcoin" not in re.sub(r"jet_bitcoin_[a-z_0-9]+|bitcoin_build_tap[a-z_]*_local_spec|bitcoin/ops.c|simplicity_bitcoin_make_tap[a-z]*\(|Programs.Bitcoin", "", t), \
        (m, re.findall(r".{30}bitcoin.{30}", re.sub(r"jet_bitcoin_[a-z_0-9]+|bitcoin_build_tap[a-z_]*_local_spec", "", t))[:3])
    t = rename.sub(lambda mo: "el_" + mo.group(1), t)
    t = t.replace("el_bitcoin_build_", "elements_build_")
    for mm in MODS:
        t = t.replace("C.jet_bitcoin_%s" % mm, "C.jet_elements_%s" % mm)
    t = sub1(t, "\nLocal Open Scope Z_scope.", "\nRequire Import C.jet_elements_tap_tags.\nLocal Open Scope Z_scope.", 1)
    t = t.replace("Programs.Bitcoin", "Programs.Elements").replace("bitcoin/ops.c", "elements/ops.c").replace("simplicity_bitcoin_make", "simplicity_make")
    t = ("(** GENERATED by elements-sha/gen-elements-tap-ports.py from [jet_bitcoin_%s]; do not edit. *)\n" % m) + t
    open("%s/jet_elements_%s.v" % (out, m), "w").write(t)
    print("ported jet_elements_" + m)
