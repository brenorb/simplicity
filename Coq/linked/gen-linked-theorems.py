#!/usr/bin/env python3
"""Generate linked/C/jet_linked_memcpy_jets.v.

For every accepted core theorem `X : memcpy_model -> STATEMENT`, emit
`X_linked : STATEMENT`, proved by applying X (compiled unchanged in the linked
tree) to `memcpy_model_holds`.  STATEMENT is copied verbatim, so a linked
theorem is the accepted contract for the linked program without the premise.
"""
import re, sys

MODULES = ["jet_core_projection_jets", "jet_core_pad_instances",
           "jet_core_fullshift_jets", "jet_core_fullshift64_jets"]
EXPECTED = 104
src_dir, out_path = sys.argv[1:3]
out = ['''(** GENERATED by linked/gen-linked-theorems.py; do not edit.

    Unconditional contracts of the memcpy-dependent core jets for the linked
    program, in which [memcpy] is the internal function proved in
    [jet_memcpy_exact].  Each statement is the accepted statement with the
    [memcpy_model] premise removed; [C.jets] here is the linked program. *)
From Coq Require Import ZArith List.
From compcert Require Import Coqlib Integers AST Ctypes Cop Clight Maps.
Require Simplicity.Alg.
Require Import Simplicity.Ty Simplicity.Word Simplicity.Translate Simplicity.BitMachine.
Require Import C.jets C.jet_exec C.jet_encoding C.jet_context_separated.
Require Import C.jet_core_pad_spec C.jet_memcpy_model.
Require Import %s.
Local Open Scope Z_scope.
''' % " ".join("C." + m for m in MODULES)]
count = 0
for mod in MODULES:
    text = open("%s/%s.v" % (src_dir, mod)).read()
    out.append("\n(** From [%s]. *)" % mod)
    for m in re.finditer(r"^Theorem (\w+) : memcpy_model ->\n(.*?)\.\nProof\.", text, re.S | re.M):
        name, stmt = m.group(1), m.group(2)
        if "memcpy_model" in stmt:
            sys.exit("%s: nested premise" % name)
        out.append("Theorem %s_linked :\n%s.\nProof. exact (%s memcpy_model_holds). Qed.\n" % (name, stmt, name))
        count += 1
    if len(re.findall(r"memcpy_model ->", text)) != len(re.findall(r"^Theorem \w+ : memcpy_model ->\n", text, re.M)):
        sys.exit("%s: conditional statement in an unexpected shape" % mod)
if count != EXPECTED:
    sys.exit("expected %d conditional theorems, found %d" % (EXPECTED, count))
open(out_path, "w").write("\n".join(out))
