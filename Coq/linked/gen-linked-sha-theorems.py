#!/usr/bin/env python3
"""Generate the unconditional linked theorems of the SHA translation unit.

For every accepted theorem `X : memcpy_model -> STATEMENT` of the listed
modules, emit `X_linked : STATEMENT` in `<module>_linked.v`, proved by
applying X (compiled unchanged in the linked tree) to `memcpy_model_holds`.
Each generated module starts with the import sentences of its source module,
so STATEMENT is read in the same scope; it is copied verbatim.
"""
import re, sys

MODULES = {
    "jet_sha_ctx8_add_jets": 10,
    "jet_sha_ctx8_add_buffer_jet": 1,
    "jet_sha_ctx8_finalize_jet": 1,
    "jet_sha_tapdata_jet": 1,
    "jet_bitcoin_annex_hash_jet": 1,
    "jet_bitcoin_outpoint_hash_jet": 1,
    "jet_bitcoin_output_hash_jet": 1,
    "jet_bitcoin_input_hash_jet": 1,
    "jet_bitcoin_input_utxo_hash_jet": 1,
    "jet_bitcoin_build_tapleaf_jet": 1,
    "jet_bitcoin_build_tapbranch_jet": 1,
}
IMPORT = re.compile(r"^(From|Require|Import|Local Open Scope|Open Scope|Local Transparent)\b")
src_dir, out_dir = sys.argv[1:3]
for mod, expected in MODULES.items():
    text = open("%s/%s.v" % (src_dir, mod)).read()
    first = re.search(r"^(Theorem|Lemma|Definition|Section|Fixpoint|Ltac|Inductive|Record|Notation|Local Notation)\b", text, re.M)
    head = re.sub(r"\(\*.*?\*\)", "", text[:first.start()], flags=re.S)
    sentences = [s.strip() for s in re.split(r"\.\s*\n", head) if s.strip()]
    imports = [s + "." for s in sentences if IMPORT.match(s)]
    if not any("C.jet_memcpy_model" in s for s in imports):
        sys.exit("%s: does not import the memcpy model" % mod)
    out = ["(** GENERATED by linked/gen-linked-sha-theorems.py; do not edit.",
           "    Accepted statements of [%s] for the memcpy-linked SHA program," % mod,
           "    with the [memcpy_model] premise discharged by [memcpy_model_holds]. *)"]
    out += imports
    out.append("Require Import C.%s.\n" % mod)
    found = re.findall(r"^Theorem (\w+) : memcpy_model ->\n(.*?)\.\nProof\.", text, re.S | re.M)
    if len(found) != expected or len(re.findall(r"^Theorem \w+ : memcpy_model ->", text, re.M)) != expected:
        sys.exit("%s: expected %d conditional theorems" % (mod, expected))
    for name, stmt in found:
        if "memcpy_model" in stmt:
            sys.exit("%s: nested premise" % name)
        out.append("Theorem %s_linked :\n%s.\nProof. exact (%s memcpy_model_holds). Qed.\n" % (name, stmt, name))
    open("%s/%s_linked.v" % (out_dir, mod), "w").write("\n".join(out))
