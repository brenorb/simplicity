#!/usr/bin/env python3
"""Generate linked/startup/jet_sha_startup_linked.v.

For every `X_startup[_env]_spec : memcpy_model -> S` of the startup-invariant
modules, emit `X_startup[_env]_linked : S` for the memcpy-linked SHA program,
proved by applying it to `memcpy_model_holds`.  S is copied verbatim.
"""
import re, sys

MODULES = {"jet_sha_startup_jets": 17, "jet_sha_startup_env_jets": 3,
           "jet_sha_startup_env_callers": 3}
IMPORT = re.compile(r"^(From|Require|Import|Local Open Scope|Open Scope|Local Transparent)\b")
src_dir, out_path = sys.argv[1:3]
requires, others, theorems = [], [], []
for mod, expected in MODULES.items():
    text = open("%s/%s.v" % (src_dir, mod)).read()
    first = re.search(r"^(Theorem|Lemma|Definition|Section|Local Ltac|Ltac)\b", text, re.M)
    head = re.sub(r"\(\*.*?\*\)", "", text[:first.start()], flags=re.S)
    for s in [x.strip() + "." for x in re.split(r"\.\s*\n", head) if x.strip()]:
        if IMPORT.match(s):
            target = requires if s.startswith(("From", "Require")) else others
            if s not in target:
                target.append(s)
    found = re.findall(r"^Theorem (\w+_startup(?:_env)?)_spec : memcpy_model ->\n(.*?)\.\nProof\.", text, re.S | re.M)
    if len(found) != expected or len(re.findall(r"memcpy_model ->", text)) != expected:
        sys.exit("%s: expected %d conditional theorems" % (mod, expected))
    for name, stmt in found:
        theorems.append("Theorem %s_linked :\n%s.\nProof. exact (%s_spec memcpy_model_holds). Qed.\n"
                        % (name, stmt, name))
runs = []
jets_text = open("%s/jet_sha_startup_jets.v" % src_dir).read()
for name in re.findall(r"^Theorem (\w+)_startup_spec : memcpy_model ->", jets_text, re.M):
    runs.append("Theorem %s_startup_runs_linked :\n  ltac:(let T := type of (%s_startup_runs memcpy_model_holds) in exact T).\n"
                "Proof. exact (%s_startup_runs memcpy_model_holds). Qed.\n" % (name, name, name))
if len(runs) != 17:
    sys.exit("expected 17 conditional run theorems")
out = ['''(** GENERATED by linked/gen-linked-startup-theorems.py; do not edit.

    SHA-unit jet contracts for the memcpy-linked SHA program whose only state
    premise is the startup invariant [sha_startup_state], which holds in the
    initial memory of that program ([sha_startup_state_initialized]) and is
    re-established by every contract.  No libc premise and no premise about
    the dispatch pointer, the maximum counter or the tag arrays remains. *)''']
out += requires
out.append("Require Import %s." % " ".join("JetStartup." + m for m in MODULES))
out.append("Require Import JetStartup.jet_sha_startup_executable JetStartup.jet_sha_startup_runs.")
out += others
out.append("")
out += theorems
out.append("(** Executability on fresh frames from any memory satisfying the invariant;\n"
           "    the statement is that of the corresponding [_startup_runs] theorem without\n"
           "    its [memcpy_model] premise. *)")
out += runs
open(out_path, "w").write("\n".join(out))
