#!/usr/bin/env python3
"""Generate linked/C/jet_frame_executable_linked.v.

For each of the registered memcpy-dependent core jets, the executability
instance `X_executable : memcpy_model -> jet_runs_on_fresh_frames f A B spec`
of C/jet_frame_executable_registry.v (compiled unchanged against the linked
program) is applied to `memcpy_model_holds`.  The resulting statements have
no premise at all: for every input the linked C code runs on fresh frames
and leaves the canonical result.
"""
import re, sys

registry, out_path = sys.argv[1:3]
text = open(registry).read()
names = re.findall(r"^Theorem (\w+)_executable :\n  ltac:\(let T := type of C\.\w+\.\w+ in\n"
                   r"        lazymatch T with memcpy_model ->", text, re.M)
if len(names) != 104:
    sys.exit("expected 104 conditional executability instances, found %d" % len(names))
out = ['''(** GENERATED by linked/gen-linked-executable.py; do not edit.

    Unconditional executability of the 104 memcpy-dependent core jets for the
    memcpy-linked program: for every input, the C function runs on freshly
    constructed frames, returns 1 and leaves [encode (spec a)] in the output
    frame.  No libc premise, no frame premise, no input restriction. *)
Require Import C.jet_memcpy_model C.jet_frame_constructible_jets.
Require C.jet_frame_executable_registry.
''']
for name in names:
    full = "C.jet_frame_executable_registry.%s_executable" % name
    out.append("Theorem %s_executable_linked :\n"
               "  ltac:(let T := type of (%s memcpy_model_holds) in exact T).\n"
               "Proof. exact (%s memcpy_model_holds). Qed.\n" % (name, full, full))
open(out_path, "w").write("\n".join(out))
